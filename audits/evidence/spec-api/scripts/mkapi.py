"""The specification API PR (user, 2026-10-16: published equation lemmas, not unfolding).
Every edit is asserted unique. Usage: python3 -I mkapi.py <worktree root>"""
import os, sys

root = sys.argv[1]
B = os.path.join(root, 'TCSlib/Complexity/TuringMachine/Build')
NS = '{ isSimp := false }'
DATA = 'pre time post lo hi'


def edit(rel, pairs):
    p = os.path.join(B, rel)
    t = open(p).read()
    for old, new in pairs:
        n = t.count(old)
        assert n == 1, (rel, n, old[:90])
        t = t.replace(old, new)
    open(p, 'w').write(t)


def bullet_before_refs(text):
    return ("\n\n## References", "\n" + text + "\n\n## References")


