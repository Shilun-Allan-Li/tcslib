#!/usr/bin/env bash
# MIG-0b round 2: regenerate the unit and every check, elaborate them, and write the logs.
# Read-only on the worktree; `lean` only through tools/leanelab.sh (no -o, no olean written);
# python3 -I for the scripts. Usage: bash runall.sh <S>
set -u
S="$1"; WT="$S/wt-r2m0b"; OL="$S/oleans-f8"; O="$S/r2-mig0b"; W="$O/work"; SC="$W/scripts"
LOG="$O/elaboration.log"; AXLOG="$O/axioms.log"
san() { sed "s|$O/|<OUT>/|g; s|$S/|<S>/|g"; }
summ() { # outfile
  local f="$1"
  echo "exit $(grep -E '^exit [0-9]+$' "$f" | cut -d' ' -f2) | errors $(grep -c ': error' "$f") | warnings $(grep -c ': warning' "$f") | of which \`declaration uses 'sorry'\` $(grep -c "declaration uses 'sorry'" "$f") | $(grep -E '^seconds [0-9]+$' "$f" | cut -d' ' -f2) s"
}
cd "$SC" || exit 1
rm -rf "$O/landing" "$O/cut" "$W/out" "$W/sig" "$W/sigout" "$W/ax" "$W/axout" "$W/lint"
python3 -I build.py "$WT" "$O" > "$W/build.out" || exit 1
python3 -I mkextras.py "$WT" "$O/Contract-mig0b-r2-unit.lean" "$O" > "$W/mkextras.out" || exit 1
python3 -I identity.py "$WT" "$O" > /dev/null || exit 1
python3 -I cutcheck2.py "$O/Contract-mig0b-r2-unit.lean" "$WT" "$O/cut" "$O/extras.lean" > "$W/cutcheck.out" || exit 1
bash "$SC/elab_all.sh" "$S" "$O/cut" "$W/out"
# Negative control: Build/CounterLoop without its one in-file Q11 proof edit.
mkdir -p "$W/neg"
python3 -I - "$O/cut/TCSlib.Complexity.TuringMachine.Build.CounterLoop.check.lean" "$W/neg/CounterLoopNoEdit.lean" <<'EOF'
import sys
t = open(sys.argv[1], encoding='utf-8').read()
old = 'by simp [counter_layout, counterLoopOrbit, roundOrbit]⟩'
assert t.count(old) == 1
open(sys.argv[2], 'w', encoding='utf-8').write(t.replace(old, 'by simp [counter_layout, counterLoopOrbit]⟩'))
EOF
bash "$SC/elab_all.sh" "$S" "$W/neg" "$W/negout"
python3 -I graphcheck.py "$WT" "$O" > "$W/graph.log" || exit 1
python3 -I sigprobe.py make "$WT" "$O" > "$W/sig.out"
bash "$SC/elab_all.sh" "$S" "$W/sig" "$W/sigout"
python3 -I sigprobe.py compare "$O" > /dev/null
python3 -I axprobe.py make "$O" > /dev/null
bash "$SC/elab_all.sh" "$S" "$W/ax" "$W/axout"
cp "$W/axout/AxProbe.lean.out" "$W/ax/AxProbe.lean.out"
python3 -I axprobe.py summary "$O" > /dev/null
# The repository's style lint, run on a copy of the landing tree, against the same files at the worktree.
mkdir -p "$W/lint/scripts" "$W/lintbase/scripts"
cp "$WT/scripts/style_lint.py" "$W/lint/scripts/"; cp "$WT/scripts/style_lint.py" "$W/lintbase/scripts/"
(cd "$O/landing" && find TCSlib -name '*.lean' | sort) > "$W/lint/files.txt"
while read -r f; do mkdir -p "$W/lint/$(dirname "$f")"; cp "$O/landing/$f" "$W/lint/$f"
  if [ -f "$WT/$f" ]; then mkdir -p "$W/lintbase/$(dirname "$f")"; cp "$WT/$f" "$W/lintbase/$f"; fi
done < "$W/lint/files.txt"
(cd "$W/lint" && python3 -I scripts/style_lint.py $(cat files.txt) > lint.out 2>&1)
(cd "$W/lintbase" && python3 -I scripts/style_lint.py $(find TCSlib -name '*.lean' | sort) > lint.out 2>&1)
python3 -I - "$W/lint/lint.out" "$W/lintbase/lint.out" > "$W/lint-delta.log" <<'EOF'
import re, sys
from collections import Counter
norm = lambda l: re.sub(r'\d+ lines', 'N lines', re.sub(r':\d+:', ':N:', l)).strip()
new = Counter(norm(l) for l in open(sys.argv[1]) if l.strip() and 'findings in' not in l)
base = Counter(norm(l) for l in open(sys.argv[2]) if l.strip() and 'findings in' not in l)
print('findings in the landing files that the worktree files do not have:')
for k, v in (new - base).items(): print(f'  {k}' + (f' (x{v})' if v > 1 else ''))
print('findings of the worktree files that the landing files no longer have:')
for k, v in (base - new).items(): print(f'  {k}' + (f' (x{v})' if v > 1 else ''))
EOF

{
echo "# MIG-0b round 2: elaboration log"
echo
echo "Tool: \`bash <S>/tools/leanelab.sh <S>/wt-r2m0b <S>/oleans-f8 <file>\` (direct \`lean\`, no \`-o\`, no"
echo "olean written). Worktree \`wt-r2m0b\`, read-only, at campaign commit \`1781a230\` (PR #84, fills-8);"
echo "olean snapshot \`oleans-f8\` (all of TCSlib at that commit). Toolchain: \`$(cat "$WT/lean-toolchain")\`."
echo "<OUT> is the round-2 output directory, <S> the scratchpad. Generated by \`work/scripts/runall.sh\`;"
echo "run $(date -u '+%Y-%m-%d %H:%M UTC')."
echo
echo "## 0. Inputs"
echo '```'
for f in TCSlib/Complexity/TuringMachine/Build/Contract.lean audits/evidence/mig0/Contract-proposed-r2.lean.txt \
  audits/evidence/mig0b/Contract-mig0b-draft.lean.txt audits/evidence/mig0b/Contract-mig0b-adapters.lean.txt; do
  echo "$(shasum -a 256 "$WT/$f" | cut -d' ' -f1)  $f ($(wc -l < "$WT/$f" | tr -d ' ') lines)"; done
echo '```'
echo
echo "## 1. Build"
echo '```'; cat "$W/build.out" | san; cat "$W/mkextras.out" | san; echo '```'
echo
echo "## 2. Cut checks: each landing module in exactly its own import closure"
echo
echo "\`python3 -I cutcheck2.py <OUT>/Contract-mig0b-r2-unit.lean <S>/wt-r2m0b <OUT>/cut <OUT>/extras.lean\`:"
echo '```'; san < "$W/cutcheck.out"; echo '```'
echo
echo "### 2a. The thirteen landing parts"
for f in "$O"/cut/*.check.lean; do b=$(basename "$f"); case "$b" in *.x1*) continue;; esac
  echo "* \`$b\` ($(wc -l < "$f" | tr -d ' ') lines): $(summ "$W/out/$b.out")"; done
echo
echo "### 2b. Extras: the edited existing files whole, the downstream probes of Q11, the fit file"
for f in "$O"/cut/*.x1*.check.lean; do b=$(basename "$f")
  echo "* \`$b\` ($(wc -l < "$f" | tr -d ' ') lines): $(summ "$W/out/$b.out")"; done
echo
echo "### 2c. Negative controls (each must fail)"
echo "* \`work/neg/CounterLoopNoEdit.lean\` (the CounterLoop part without its \`roundOrbit\` simp argument): $(summ "$W/negout/CounterLoopNoEdit.lean.out")"
for x in 111 112; do b=$(basename "$(ls "$O"/cut/*.x$x.check.lean)"); echo "* \`$b\`: $(summ "$W/out/$b.out")"; done
echo
echo "### 2d. Every message other than the expected ones"
echo
echo "Expected: the one \`sorry\` of \`Turing.FinTM.exists_alphabetReduction_lockstep\` in every check whose"
echo "closure holds part 7, and the warnings that the worktree's own files already give when elaborated"
echo "as copies (\`work/orig\`): \`Build/Seam\` 5 unused variables, \`Build/Embed\` 2, \`Finite\` 2 unused simp"
echo "arguments, \`Build/Catalog\` 90, \`CodeSimulator\` 3 (2 of them its own \`sorry\`s)."
echo '```'
for f in "$W"/out/*.out; do case "$f" in *.x111.*|*.x112.*) continue;; esac
  grep -E ": (error|warning)" "$f" | grep -v "declaration uses 'sorry'" | sed 's|.*/cut/||' \
    | sed -E 's/\.check\.lean:[0-9]+:[0-9]+:/:/'; done | sort | uniq -c
echo '```'
echo
echo "## 3. Identity and statement freeze (\`identity.py\`)"
echo
cat "$W/identity.log"
echo
echo "## 4. Signature freeze (\`sigprobe.py\`: \`#check @Name\` under \`pp.all\`, old modules against the new closure)"
for f in "$W"/sigout/*.out; do echo "* \`$(basename "$f" .out)\`: $(summ "$f")"; done
echo
cat "$W/signatures.log"
echo
echo "## 5. Axioms (\`axprobe.py\`; full prints in \`axioms.log\`)"
for f in "$W"/axout/*.out; do echo "* \`$(basename "$f" .out)\`: $(summ "$f")"; done
echo
cat "$W/axioms-summary.log"
echo
echo "## 6. Style lint (the repository's \`scripts/style_lint.py\`, copied; landing files against worktree files)"
echo '```'; cat "$W/lint-delta.log"; echo '```'
echo
echo "## 7. Import graph of the landing tree (\`graphcheck.py\`)"
echo '```'; cat "$W/graph.log"; echo '```'
} > "$LOG"
{
echo "# MIG-0b round 2: axiom prints"
echo
echo "\`#print axioms\` for every public declaration of the thirteen parts and of the fit namespace,"
echo "appended to a copy of the fit file (\`work/ax/AxProbe.lean\`), elaborated as in \`elaboration.log\`."
echo
cat "$W/axioms-summary.log"
echo
echo '```'
grep -E "depends on axioms|does not depend on any axioms" "$W/ax/AxProbe.lean.out" | san
echo '```'
} > "$AXLOG"
echo "done: $LOG"
