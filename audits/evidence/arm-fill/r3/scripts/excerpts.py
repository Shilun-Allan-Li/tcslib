"""Source excerpts for screen pairs whose library-side file was absent from round 2's bundle
(round-2 finding text, "Source counterparts absent from this bundle"). For each pair: both ends
with file:lines at the screened tree, the screen's shared tiles (greedy, blocks >= 25 whitespace-
free characters, as the screen computes them) for the pair's largest directed hit, and the raw
source lines of the library-side declaration (its whole span, comments included), numbered.
usage: python3 -I excerpts.py <pairs3.tsv> <classify3.tsv> <tree-root> <out.md> [--tip <pairs3-tip.tsv>] pid [pid ...]
With --tip, each excerpt also gives the pair's hits and library lines at the tip."""
import os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from leancore3 import decls
ptsv, ctsv, root, dst = sys.argv[1:5]; want = sys.argv[5:]
tip = {}
if want[:1] == ['--tip']:
    tip = {c[0]: c for c in (l.rstrip('\n').split('\t') for l in open(want[1], encoding='utf-8')) if c[0] != 'pid'}; want = want[2:]
rows = {c[0]: c for c in (l.rstrip('\n').split('\t') for l in open(ptsv, encoding='utf-8')) if c[0] != 'pid'}
cls = {c[0]: c for c in (l.rstrip('\n').split('\t') for l in open(ctsv, encoding='utf-8')) if c[0] != 'pid'}
def lcs(a, b):
    lo, hi, best = 0, min(len(a), len(b)), ''
    while lo < hi:
        mid = (lo + hi + 1) // 2
        subs = {b[i:i + mid] for i in range(len(b) - mid + 1)}
        hit = next((a[i:i + mid] for i in range(len(a) - mid + 1) if a[i:i + mid] in subs), None)
        if hit is not None: lo, best = mid, hit
        else: hi = mid - 1
    return lo, best
def tiles(a, b):
    out = []
    while True:
        n, seg = lcs(a, b)
        if n < 25: return out
        out.append(seg); a = a.replace(seg, '\x00', 1); b = b.replace(seg, '\x01', 1)
cache = {}
def get(p, n):
    if p not in cache:
        txt = open(os.path.join(root, p), encoding='utf-8').read()
        cache[p] = ({d['name']: d for d in decls(txt)}, txt.split('\n'))
    return cache[p][0][n], cache[p][1]
o = open(dst, 'w', encoding='utf-8')
o.write('# Source excerpts: the library counterparts round 2 could not show (25 pairs), and L033\'s\n\n'
        'L033 is the deferred G-rep row; its counterpart file, `CookLevin/Hardness.lean` (470 KB), is not bundled whole this round.\n\n')
o.write('Generated by `scripts/excerpts.py` at the base tree. Paths relative to the repository root. '
        'Each excerpt is the library-side declaration\'s whole span (raw source, comments kept, numbered); '
        'the shared tiles are the whitespace-free text the screen matched in the largest directed hit. '
        'Class and basis are round 3\'s (`classify3.tsv`).\n\n')
for pid in want:
    if pid not in rows:
        o.write(f'## {pid}\n\nNot a pair of this screen (absent at this tree).\n\n'); continue
    c = rows[pid]; k = cls[pid]
    A, B = (c[2], c[3]), (c[7], c[8])
    da, la = get(*A); db, lb = get(*B)
    # largest directed hit
    best = max(c[12].split('; '), key=lambda h: int(h.split()[1].split('/')[0]))
    a2b = best.startswith('A>B')
    ts = tiles(db['body'], da['body']) if a2b else tiles(da['body'], db['body'])
    o.write(f'## {pid}: `{A[1]}` ~ `{B[1]}` — class {k[2]}, group {k[4]}\n\n')
    o.write(f'- Copy side (added file): `{A[0]}:{c[4]}` ({c[5]} code lines, {c[6]} body chars)\n')
    o.write(f'- Library side: `{B[0]}:{c[9]}` ({c[10]} code lines, {c[11]} body chars)\n')
    o.write(f'- Directed hits: {c[12]}; basis: {k[5]}\n')
    if tip:
        tc = tip.get(pid)
        if tc is None: o.write('- At the tip: not on the screen\n')
        else: o.write(f'- At the tip: library side `{tc[7]}:{tc[9]}`; hits {tc[12]}' + (' (unchanged)' if tc[12] == c[12] and tc[9] == c[9] else ' (lines moved, hits unchanged)' if tc[12] == c[12] else ' (hits changed)') + '\n')
    o.write(f'- Shared tiles of the largest hit ({sum(map(len, ts))} chars):\n')
    for t in ts: o.write(f'  - `{t}`\n')
    o.write(f'\nLibrary-side source, `{B[0]}` lines {db["l0"]}–{db["l1"]}:\n\n```lean\n')
    for i in range(db['l0'], db['l1'] + 1): o.write(f'{i:5d}  {lb[i - 1]}\n')
    o.write('```\n\n')
print('excerpts written', len(want))
