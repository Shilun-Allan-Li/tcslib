"""Cut-check files of the U2 unit, per home, plus the consumer probe (read-only on its inputs;
standard library only).

Usage: python3 -I mkcuts.py <base root> <landed root> <Diagonal Part 1 file> <probes dir> <out>

The snapshot holds the base versions of the touched modules, so a module that imports a landed
module is checked by concatenation: the union of the chain's imports minus the chain's modules,
then each chain module's body (everything after its import header) inside `section`/`end`, in
order, then `#print axioms` for the checked module's public declarations. A module whose imports
are all unchanged is checked as itself. Files written (each with a `.lean` suffix):
  StepBlockLoop.check   the landed StepBlockLoop (its imports are unchanged)
  Codes2Tape.check      the landed Codes2Tape (its imports are unchanged)
  UniversalK.cut        Codes2Tape (landed), UniversalK
  SelfUniversal.cut     Codes2Tape, UniversalK, SelfUniversal (landed)
  TuringMachine.cut     Codes2Tape, UniversalK, SelfUniversal, the facade (landed)
  CodeSimulator.cut     StepBlockLoop (landed), CodeSimulator (base): the landed host's importer
  CodeSimulator.base    CodeSimulator (base), its baseline
  SelfUniversal.base    SelfUniversal (base), its baseline
  U2Consumer.cut        Diagonal Part 1, Codes2Tape, UniversalK, the consumer probe body
"""
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
from cutcheck_lib import split_header, prints  # noqa: E402

TM = "TCSlib.Complexity.TuringMachine"


def rel(m):
    return os.path.join(*m.split(".")) + ".lean"


def main():
    base, landed, diag, probes, out = sys.argv[1:6]
    os.makedirs(out, exist_ok=True)
    LANDED = {f"{TM}.Build.StepBlockLoop", f"{TM}.Codes2Tape", f"{TM}.UniversalK",
              f"{TM}.SelfUniversal", "TCSlib.Complexity.TuringMachine"}

    def src_of(m):
        if m == "TCSlib.Complexity.TimeHierarchy.Diagonal":
            return open(diag, encoding="utf-8").read(), "Diagonal Part 1, as in its gate"
        if m == "U2Consumer":
            return open(os.path.join(probes, "U2Consumer.body.lean"), encoding="utf-8").read(), \
                "the consumer probe"
        root = landed if m in LANDED else base
        return open(os.path.join(root, rel(m)), encoding="utf-8").read(), \
            ("landed" if m in LANDED else "base")

    def write(name, chain, extra=(), print_of=None):
        union, bodies = list(extra), []
        for m in chain:
            src, origin = src_of(m)
            if m == "U2Consumer":
                imps, body = [], src
            else:
                imps, body = split_header(src)
            for i in imps:
                if i not in chain and i not in union:
                    union.append(i)
            bodies.append(f"\n-- ════ body of {m} ({origin}) ════\nsection\n{body.strip()}\n\nend\n")
        pr, n = prints(src_of(print_of)[0]) if print_of else ("\n", 0)
        text = (f"-- Cut check (generated by mkcuts.py): {name}.\n"
                + "".join(f"import {i}\n" for i in union) + "".join(bodies)
                + f"\n-- ════ axioms of {print_of}'s public declarations ({n}) ════" + pr)
        open(os.path.join(out, name + ".lean"), "w", encoding="utf-8").write(text)
        print(f"{name}: {len(chain)} bodies, {len(union)} imports, {n} axiom prints")

    def whole(name, m, root):
        src = open(os.path.join(root, rel(m)), encoding="utf-8").read()
        pr, n = prints(src)
        open(os.path.join(out, name + ".lean"), "w", encoding="utf-8").write(
            src.rstrip("\n") + f"\n\n-- ════ axioms of {m}'s public declarations ({n}) ════" + pr)
        print(f"{name}: the file itself ({root == landed and 'landed' or 'base'}), {n} axiom prints")

    whole("StepBlockLoop.check", f"{TM}.Build.StepBlockLoop", landed)
    whole("Codes2Tape.check", f"{TM}.Codes2Tape", landed)
    write("UniversalK.cut", [f"{TM}.Codes2Tape", f"{TM}.UniversalK"], print_of=f"{TM}.UniversalK")
    write("SelfUniversal.cut", [f"{TM}.Codes2Tape", f"{TM}.UniversalK", f"{TM}.SelfUniversal"],
          print_of=f"{TM}.SelfUniversal")
    write("TuringMachine.cut", [f"{TM}.Codes2Tape", f"{TM}.UniversalK", f"{TM}.SelfUniversal",
                                "TCSlib.Complexity.TuringMachine"])
    write("CodeSimulator.cut", [f"{TM}.Build.StepBlockLoop", f"{TM}.CodeSimulator"],
          print_of=f"{TM}.CodeSimulator")
    whole("CodeSimulator.base", f"{TM}.CodeSimulator", base)
    whole("SelfUniversal.base", f"{TM}.SelfUniversal", base)
    write("U2Consumer.cut", ["TCSlib.Complexity.TimeHierarchy.Diagonal", f"{TM}.Codes2Tape",
                             f"{TM}.UniversalK", "U2Consumer"], extra=["Mathlib.Data.Nat.Log"])


if __name__ == "__main__":
    main()
