"""Reconcile the independent proof fill without running Lean or dispatching work."""

from collections import Counter
import hashlib
import json
from pathlib import Path
import re
import runpy
import subprocess


HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[3]
E = HERE / 'evidence'
OLD = ROOT / 'briefs/lwe-sis-constructions/gates/08-construction-statements/evidence'
STANDARD = {'propext', 'Classical.choice', 'Quot.sound'}
SCOPES = ['Encoding', 'LWE', 'SIS', 'Encryption/Symmetric/Regev',
    'Encryption/PublicKey/Regev', 'Hashing/SIS', 'Pseudorandom/Generators/LWE',
    'TrapdoorFunctions']


def write(name, value):
    (E / name).write_text(json.dumps(value, indent=2) + '\n')


def main():
    runpy.run_path(str(HERE / 'verify_freeze.py'))['main']()
    runpy.run_path(str(HERE / 'compare_types.py'))['main']()
    freeze = json.loads((E / 'freeze.json').read_text())
    assert freeze['filled_targets'] == freeze['changed_theorem_bodies'] == 31
    assert freeze['remaining_direct_admissions'] == 70
    targets = json.loads((E / 'targets.json').read_text())
    filled = {x['name'] for x in targets if not x['directly_admitted']}
    remaining = {x['name'] for x in targets if x['directly_admitted']}
    sources = json.loads((OLD / 'source-declarations.json').read_text())
    source_names = {x['name'] for x in sources}
    baseline = {x['name']: x for x in json.loads((OLD / 'elaborated-constants.json').read_text())}
    assert len(baseline) == 575 and len(source_names) == 220
    types = json.loads((E / 'type-probe-comparison.json').read_text())
    assert types['existing_owned_constants_compared'] == 575
    assert types['all_existing_level_params_and_type_expr_representations_exactly_equal']
    migrated_names = {
        'TCSlib.Cryptography.Encoding.DyadicUniform.bitsToMatrix.congr_simp',
        'TCSlib.Cryptography.Encoding.DyadicUniform.bitsToVector.congr_simp'}
    probe = json.loads((E / 'axiom-probe/checks.json').read_text())
    assert len(probe) == 1 and probe[0]['exit_code'] == probe[0]['error_lines'] == 0
    assert probe[0]['fresh_olean']
    raw = (ROOT / probe[0]['log']).read_text()
    printed = {}
    for m in re.finditer(r"'([^']+)' depends on axioms:\s*\[(.*?)\]|'([^']+)' does not depend on any axioms", raw, re.S):
        printed[m[1] or m[3]] = [] if m[3] else sorted(x.strip() for x in m[2].split(',') if x.strip())
    backing = json.loads((OLD / 'backing-contracts.json').read_text())
    assert set(printed) == source_names | set(backing)
    assert all(set(printed[n]) <= STANDARD for n in backing)
    rows, axioms = [], {}
    for line in raw.splitlines():
        if line.startswith('COMBINED_CONSTANT|'):
            _, module, name, kind, private = line.split('|')
            rows.append(dict(module=module, name=name, kind=kind, private=private == 'true'))
        if line.startswith('COMBINED_AXIOMS|'):
            _, name, labels = line.split('|')
            axioms[name] = sorted(filter(None, labels.split(',')))
    assert len(rows) == len(axioms) == len({x['name'] for x in rows})
    assert set(baseline) <= set(axioms)
    added, migrated = [], []
    for row in rows:
        n = row['name']; row['axioms'] = axioms[n]
        assert row['kind'] != 'axiom' and set(row['axioms']) <= STANDARD | {'sorryAx'}, row
        if n in baseline:
            assert all(row[k] == baseline[n][k] for k in ['kind', 'private']), row
            if row['module'] != baseline[n]['module']:
                assert n in migrated_names and baseline[n]['category'] == 'compiler auxiliary', row
                assert baseline[n]['module'] == 'TCSlib.Cryptography.LWE.Sampling', row
                assert row['module'] == 'TCSlib.Cryptography.Encoding.DyadicUniform', row
                migrated.append(dict(name=n, previous_module=baseline[n]['module'],
                    current_module=row['module'], kind=row['kind'], private=row['private'],
                    axioms=row['axioms'], elaborated_type_exactly_preserved=True,
                    reason='Autogenerated congruence rule is first needed by a filled owner-module proof instead of the later Sampling module. No handwritten source declaration moved.'))
            if n not in filled:
                assert row['axioms'] == baseline[n]['axioms'], row
            row['category'] = 'filled source theorem' if n in filled else baseline[n]['category']
        else:
            assert any(s in n for s in ['._proof_', '.congr_simp', '._simp_', '.proof_']), row
            assert set(row['axioms']) <= STANDARD, row
            row['category'] = 'new compiler auxiliary'; added.append(row)
        assert ('sorryAx' in row['axioms']) == (n in remaining), row
    assert all(set(axioms[n]) <= STANDARD for n in filled)
    assert {x['name'] for x in migrated} == migrated_names
    for n in source_names:
        assert printed[n] == axioms[n]
    write('elaborated-constants.json', sorted(rows, key=lambda x: x['name']))
    write('new-compiler-constants.json', sorted(added, key=lambda x: x['name']))
    write('compiler-origin-changes.json', sorted(migrated, key=lambda x: x['name']))
    write('backing-contract-axioms.json', [dict(name=n, axioms=printed[n]) for n in backing])
    order = (E / 'module-order.txt').read_text().splitlines()
    sweep = json.loads((E / 'final-sweep/checks.json').read_text())
    assert len(sweep) == len(order) == 144 and [x['module'] for x in sweep] == order
    new_modules = set(json.loads((OLD / 'new-math-modules.json').read_text()))
    warnings = Counter(); other_warnings = []
    for row in sweep:
        assert row['exit_code'] == row['error_lines'] == 0 and row['fresh_olean'], row
        data = (ROOT / (row['module'] + '.lean')).read_bytes()
        snapshot = E / 'final-sweep/source-snapshots' / (row['module'] + '.lean')
        assert data == snapshot.read_bytes() and hashlib.sha256(data).hexdigest() == row['source_sha256']
        log = (ROOT / row['log']).read_text()
        assert not re.search(r'\berror(?:\([^)]*\))?:', log)
        assert log.count("declaration uses 'sorry'") == row['admission_warnings']
        warnings['owned' if row['module'] in new_modules else 'inherited'] += row['admission_warnings']
        current_other = [s.split('warning:', 1)[1] for s in log.splitlines()
            if 'warning:' in s and "declaration uses 'sorry'" not in s]
        old_log = (OLD / 'audit-final-sweep' / Path(row['log']).name).read_text()
        previous_other = [s.split('warning:', 1)[1] for s in old_log.splitlines()
            if 'warning:' in s and "declaration uses 'sorry'" not in s]
        assert current_other == previous_other, (row['module'], current_other, previous_other)
        if current_other:
            other_warnings.append(dict(module=row['module'], warnings=current_other, unchanged=True))
    assert warnings == {'owned': 70, 'inherited': 17}
    write('unchanged-non-admission-warnings.json', other_warnings)
    pin = (E / 'source-pin.txt').read_text().strip()
    source_files = []
    for old in json.loads((OLD / 'source-freeze.json').read_text())['files']:
        path = old['path']; data = (ROOT / path).read_bytes()
        assert data == subprocess.check_output(['git', 'show', pin + ':' + path], cwd=ROOT), path
        source_files.append(dict(path=path, bytes=len(data), sha256=hashlib.sha256(data).hexdigest()))
    write('source-freeze.json', dict(source_pin=pin, statement_freeze=freeze['statement_source'],
        proof_baseline=freeze['proof_baseline'], files=source_files))
    counts = []
    for scope in SCOPES:
        result = subprocess.run(['python3', '-I', 'scripts/campaign_style_lint.py',
            'TCSlib/Cryptography/' + scope], cwd=ROOT, capture_output=True, text=True)
        (E / ('style-' + scope.replace('/', '-') + '.log')).write_text(result.stdout + result.stderr)
        match = re.search(r'style_lint: (\d+) FAIL, (\d+) WARN over (\d+) files', result.stdout)
        assert result.returncode == 0 and match
        counts.append(tuple(map(int, match.groups())))
    style = tuple(map(sum, zip(*counts))); assert style == (0, 2, 41), style
    summary = dict(source_pin=pin, statement_freeze=freeze['statement_source'],
        proof_baseline=freeze['proof_baseline'], pr=250, target='cryptography/lwe-sis-constructions',
        filled_proofs=31, remaining_direct_admissions=70, changed_math_modules=7,
        source_declarations=220, preserved_closed_source_readers=62,
        baseline_owned_constants=575, owned_constants=len(rows), new_compiler_auxiliaries=len(added),
        earlier_compiler_origin_changes=len(migrated), existing_elaborated_types_compared=575,
        owned_constants_with_sorryAx=70, selected_filled_targets_with_sorryAx=0,
        backing_contracts=len(backing), fresh_modules=144,
        fresh_seconds=round(sum(x['seconds'] for x in sweep), 3),
        axiom_probe_seconds=probe[0]['seconds'], admission_warnings=dict(warnings),
        unchanged_non_admission_warning_count=sum(len(x['warnings']) for x in other_warnings),
        source_freeze_files=len(source_files), style_failures=0, style_warnings=2, style_files=41,
        whole_library_root_checked=False, shared_proposals_applied=False,
        source_policy_closed=False, external_proof_gate_closed=False,
        merges_performed=0, external_jobs_dispatched=0, pids_killed=[])
    write('summary.json', summary)
    print(json.dumps(summary, indent=2))


if __name__ == '__main__':
    main()
