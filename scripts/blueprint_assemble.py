r"""Assemble the published textbook from blueprint/organization.json.

Every local module must be assigned explicitly. External-project metadata stays
excluded. Wrappers are generated into chapter/textbook/ and never enumerated as
modules. --check is read-only; ordinary assembly is deterministic and idempotent.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

BASE = Path(__file__).resolve().parent.parent
CHAPTER_DIR = BASE / 'blueprint' / 'src' / 'chapter'
MAIN_TEX = CHAPTER_DIR / 'main.tex'
MANIFEST = BASE / 'blueprint' / 'organization.json'
sys.path.insert(0, str(BASE))
from scripts import dataset_projects as dp
from scripts.blueprint_structure import (INPUT_RE, normalize_headings, resolve_inputs,
                                         uncomment, verify_snapshot)
GENERATED = '% Generated by scripts/blueprint_assemble.py; edit blueprint/organization.json.\n'


def existing_inputs(text: str) -> set[str]:
    return set(INPUT_RE.findall(uncomment(text)))


def dataset_only(rel: str) -> bool:
    """External projects supply dataset metadata, never TCSlib website chapters."""
    return rel.split('/', 1)[0] in (set(dp.projects()) - {'TCSlib'})


def published_inputs(text: str) -> str:
    return INPUT_RE.sub(lambda m: '' if dataset_only(m.group(1)) else m.group(0), text)


def all_chapter_files() -> list[str]:
    return sorted(rel for tex in CHAPTER_DIR.rglob('*.tex')
                  if (rel := tex.relative_to(CHAPTER_DIR).as_posix()) != 'main.tex'
                  and not rel.startswith('textbook/') and not dataset_only(rel))


def load_manifest(path: Path = MANIFEST, modules: list[str] | None = None) -> dict:
    data = json.loads(path.read_text())
    if data.get('schema_version') != 1 or not data.get('parts'):
        raise ValueError(f'{path}: expected schema_version=1 and nonempty parts')
    available = set(all_chapter_files() if modules is None else modules)
    assigned, ids, errors = {}, set(), []
    for part in data['parts']:
        for item in [part, *part.get('chapters', [])]:
            id = item.get('id', '')
            if not re.fullmatch(r'[a-z][a-z0-9-]*', id) or id in ids:
                errors.append(f'Invalid or duplicate stable id: {id!r}')
            ids.add(id)
            title = item.get('title', '')
            if not title or any(c in title for c in '{}%\\\n'):
                errors.append(f'{id}: invalid display title')
        if not part.get('chapters'):
            errors.append(f"{part['id']}: empty part")
        for chapter in part.get('chapters', []):
            if not chapter.get('modules'):
                errors.append(f"{chapter['id']}: empty chapter")
            for rel in chapter.get('modules', []):
                if rel in assigned:
                    errors.append(f"Duplicate module {rel}: {assigned[rel]} and {chapter['id']}")
                assigned[rel] = chapter['id']
                if rel not in available:
                    errors.append(f"{chapter['id']}: missing or excluded module {rel}")
    for rel in sorted(available - assigned.keys()):
        errors.append(f'Unassigned published module {rel}: add it to a chapter in {path}')
    if errors:
        raise ValueError('\n'.join(errors))
    return data


def module_chapters(data: dict) -> dict[str, str]:
    return {rel: c['id'] for p in data['parts'] for c in p['chapters'] for rel in c['modules']}


def planned_files(data: dict) -> dict[Path, str]:
    owners = module_chapters(data)
    nested = set()
    errors = []
    # Nested sources retain their original input position. Include their parent
    # only in the wrapper; prohibit cross-chapter inclusion and multiple parents.
    for rel in owners:
        resolved = resolve_inputs(CHAPTER_DIR, rel)
        for key in ('missing', 'repeated', 'cycles'):
            if resolved[key]:
                errors.append(f'{rel}: nested {key}: {resolved[key]}')
        direct = INPUT_RE.findall(uncomment((CHAPTER_DIR / rel).read_text()))
        for child in direct:
            child = child if child.endswith('.tex') else child + '.tex'
            if child not in owners or owners[child] != owners[rel]:
                errors.append(f'{rel}: nested input {child} must be assigned to the same chapter')
            if child in nested:
                errors.append(f'{child}: nested input has multiple parents')
            nested.add(child)
    if errors:
        raise ValueError('\n'.join(errors))
    main = [GENERATED.rstrip(), r'\tableofcontents']
    outputs = {}
    for part in data['parts']:
        main.append(f"\\part{{{part['title']}}}")
        for chapter in part['chapters']:
            name = f"textbook/{chapter['id']}.tex"
            main.append(f'\\input{{chapter/{name}}}')
            lines = [GENERATED.rstrip(), f"\\chapter{{{chapter['title']}}}",
                     f"\\label{{chapter:{chapter['id']}}}"]
            lines.extend(f'\\input{{chapter/{rel}}}' for rel in chapter['modules'] if rel not in nested)
            outputs[CHAPTER_DIR / name] = '\n'.join(lines) + '\n'
    outputs[MAIN_TEX] = '\n'.join(main) + '\n'
    for rel in owners:
        path = CHAPTER_DIR / rel
        outputs[path] = normalize_headings(path.read_text(), rel)
    return outputs


def assemble(check: bool = False, manifest: Path = MANIFEST) -> int:
    outputs = planned_files(load_manifest(manifest))
    changed = [p for p, text in outputs.items() if not p.exists() or p.read_text() != text]
    stale = sorted(set((CHAPTER_DIR / 'textbook').glob('*.tex')) - outputs.keys())
    for path in set(stale) | {p for p in outputs if p.parent.name == 'textbook' and p.exists()}:
        if not path.read_text().startswith(GENERATED):
            raise ValueError(f'Refusing to overwrite/remove non-generated wrapper {path}')
    if check:
        if changed or stale:
            print(f'Assembly needed: {len(changed)} changed/missing files, {len(stale)} stale wrappers. Run scripts/blueprint_assemble.py.')
            return 1
    else:
        for path in changed:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(outputs[path])
        for path in stale:
            path.unlink()
    print(f'Textbook assembly: {len(all_chapter_files())} modules; {len(changed)} files changed; {len(stale)} obsolete wrappers.')
    return 0


def chapter_sizes(data: dict) -> list[dict]:
    """Source-based sizes, independent of render tools and generated page numbers."""
    from scripts.blueprint_structure import file_record
    rows = []
    for part in data['parts']:
        for chapter in part['chapters']:
            sources = []
            for rel in chapter['modules']:
                text = (CHAPTER_DIR / rel).read_text()
                sources.append({'file': rel, 'lines': len(text.splitlines()),
                                'declarations': file_record(text)['declarations']})
            rows.append({'part': part['id'], 'id': chapter['id'], 'title': chapter['title'],
                         'modules': len(sources), 'lines': sum(s['lines'] for s in sources),
                         'declarations': sum(s['declarations'] for s in sources),
                         'sources': sources})
    return rows


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--check', action='store_true')
    ap.add_argument('--sizes', action='store_true', help='Print deterministic chapter-size JSON; do not assemble')
    ap.add_argument('--manifest', type=Path, default=MANIFEST)
    ap.add_argument('--verify-preservation', type=Path, metavar='BASELINE',
                    help='Read-only verification against a pre-organization snapshot')
    args = ap.parse_args()
    try:
        if args.sizes:
            print(json.dumps(chapter_sizes(load_manifest(args.manifest)), indent=2, ensure_ascii=False))
            return 0
        if args.verify_preservation:
            print(json.dumps(verify_snapshot(CHAPTER_DIR, json.loads(args.verify_preservation.read_text())), sort_keys=True))
            return 0
        return assemble(args.check, args.manifest)
    except (ValueError, KeyError, OSError) as error:
        print(f'ERROR: {error}', file=sys.stderr)
        return 1


if __name__ == '__main__':
    raise SystemExit(main())
