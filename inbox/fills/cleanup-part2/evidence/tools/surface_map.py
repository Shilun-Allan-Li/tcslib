#!/usr/bin/env python3
"""Render a surface_diff JSON as the old→new declaration map (markdown).
python3 -I surface_map.py <surface.json> <out.md> <base> <head>"""
import sys, json
r = json.load(open(sys.argv[1])); out = open(sys.argv[2], 'w'); base, head = sys.argv[3], sys.argv[4]
w = out.write
w(f'# Declaration map `{base[:9]}` → `{head[:9]}` (owned files, source level)\n\n')
w('Generated by `tools/surface_diff.py` + `tools/surface_map.py`: declarations keyed by full name '
  '(private ones by path::name); headers are attribute+modifier+signature texts with comments removed '
  'and whitespace collapsed; namespace-prefixed self references normalized.\n\n')
w(f"Summary: {json.dumps(r['summary'])}; public only: {json.dumps(r['summary_public'])}\n\n")
def vis(x): return 'private' if x.get('private') else 'public'
w('## Removed\n\n')
for x in r['removed']:
    w(f"* `{x['name']}` ({vis(x)} {x['kind']}, `{x['path']}`:{x['line']})\n  * old header: `{x['header'][:600]}`\n")
w('\n## Moved (same full name, new home)\n\n')
for x in r['moved']:
    w(f"* `{x['name']}` ({vis(x)} {x['kind']}): `{x['from']}` → `{x['to']}`; header {'unchanged' if x['header_unchanged'] else 'respelled (namespace prefix only)'}\n")
w('\n## Header changed\n\n')
for x in r['header_changed']:
    w(f"* `{x['name']}` ({vis(x)} {x['kind']}, `{x['path']}`)\n  * old: `{x['base'][:600]}`\n  * new: `{x['head'][:600]}`\n")
w('\n## Definition bodies changed\n\n')
for x in r['body_changed']:
    w(f"* `{x['name']}` ({vis(x)} {x['kind']}, `{x['path']}`)\n  * old body: `{x['base_body'][:400]}`\n  * new body: `{x['head_body'][:400]}`\n")
w('\n## Added\n\n')
for x in r['added']:
    w(f"* `{x['name']}` ({vis(x)} {x['kind']}, `{x['path']}`:{x['line']}): `{x['header'][:300]}`\n")
