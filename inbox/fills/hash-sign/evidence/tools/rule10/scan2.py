"""scan2.py <items-phase1.json> <kinds-log> <out.json>: classify every explicit item.
Resolution: the first existing candidate in Lean's lookup order as generated by scan1 (innermost
namespace first, private, then opened namespaces); `.eq_N`/`.eq_def`/`.eq_unfold` read their target."""
import sys, json, collections
items = json.load(open(sys.argv[1]))['items']; kinds = {}
for line in open(sys.argv[2], encoding='utf-8'):
    if line.startswith('EXPLICIT_KIND '):
        r = json.loads(line[len('EXPLICIT_KIND '):]); kinds[r['spelling']] = r
def resolve(names):
    for n in names:
        if n in kinds: return kinds[n]
    return None
out = []
for it in items:
    r = resolve(it['candidates'])
    target = None
    if it['eqn_target']:
        tc = [c for c in it['candidates'] if not c.endswith(it['head'].rsplit('.', 1)[-1]) or c.endswith(it['eqn_target'])]
        target = resolve([c[: -len(it['head'])] + it['eqn_target'] if c.endswith(it['head']) else c for c in it['candidates']])
    d = target if it['eqn_target'] and target and target['kind'] in ('def', 'opaque') else (r if r and r['kind'] in ('def', 'opaque') else None)
    if d:
        tcs = (d['home'] or '').startswith('TCSlib')
        if (d['home'] or '').startswith(('Lean.Meta.Tactic.Simp.BuiltinSimprocs', 'Mathlib.Tactic.Simproc')): cls = 'SIMPROC'
        elif d['home'] == it['module']: cls = 'OWNED_DEFINITION'
        elif tcs: cls = 'FOREIGN_TCSLIB_DEFINITION'
        else: cls = 'FOREIGN_CORE_MATHLIB_DEFINITION'
        sub = 'projection' if d['projection'] else ('abbrev' if d['abbrev'] else ('instance' if d['instance'] else d['status']))
        via = 'equation-lemma' if it['eqn_target'] and target else 'name'
    elif r:
        cls, sub, via = {'theorem': 'THEOREM', 'constructor': 'CONSTRUCTOR', 'inductive': 'TYPE', 'recursor': 'RECURSOR',
                         'axiom': 'AXIOM'}.get(r['kind'], r['kind'].upper()), r['kind'], 'name'
    else:
        cls, sub, via = 'LOCAL_OR_UNRESOLVED', None, None
    o = {k: it[k] for k in ('file', 'line', 'tactic', 'item', 'head', 'declaration', 'declaration_status', 'touched')}
    o.update(classification=cls, subkind=sub, via=via, resolved=(d or r or {}).get('name'), resolved_home=(d or r or {}).get('home'))
    out.append(o)
foreign = [o for o in out if o['classification'].startswith('FOREIGN')]
summary = dict(items=len(out), by_class=dict(collections.Counter(o['classification'] for o in out)),
               foreign_items=len(foreign), foreign_in_touched=[o for o in foreign if o['touched']],
               foreign_by_file_touched=dict(collections.Counter((o['file'], o['touched']) for o in foreign).most_common()) if False else
                   {f'{k[0]}|touched={k[1]}': v for k, v in collections.Counter((o['file'], o['touched']) for o in foreign).items()},
               foreign_subkinds=dict(collections.Counter((o['classification'], o['subkind']) for o in foreign).items()) if False else
                   {f'{k[0]}|{k[1]}': v for k, v in collections.Counter((o['classification'], o['subkind']) for o in foreign).items()})
json.dump(dict(summary=summary, items=out), open(sys.argv[3], 'w'), indent=1)
print(json.dumps({k: v for k, v in summary.items() if k != 'foreign_in_touched'}, indent=1))
for o in summary['foreign_in_touched']: print('TOUCHED-FOREIGN', o['file'], o['line'], o['declaration'], o['tactic'], o['item'], o['resolved'], o['subkind'])
