import collections
import json
import pathlib
import re
import subprocess

repo = pathlib.Path('/private/tmp/hash-sign-fill/repo')
base = 'eff2dcd0a63f0c371118a17c67b9a5dfc046f4e9'
commit = '8e4234934690fe4e3e00e46965112998e1d09a31'
paths = subprocess.check_output(['git', 'diff', '--name-only', base, commit], cwd=repo, text=True).splitlines()

def clean(source):
    out = []
    index = 0
    depth = 0
    line_comment = False
    quoted = False
    while index < len(source):
        char = source[index]
        pair = source[index:index + 2]
        if depth:
            if pair == '/-':
                depth += 1
                out.extend('  ')
                index += 2
            elif pair == '-/':
                depth -= 1
                out.extend('  ')
                index += 2
            else:
                out.append('\n' if char == '\n' else ' ')
                index += 1
        elif line_comment:
            if char == '\n':
                line_comment = False
                out.append(char)
            else:
                out.append(' ')
            index += 1
        elif quoted:
            if char == '\\' and index + 1 < len(source):
                out.extend('  ')
                index += 2
            else:
                if char == '"':
                    quoted = False
                out.append('\n' if char == '\n' else ' ')
                index += 1
        elif pair == '/-':
            depth = 1
            out.extend('  ')
            index += 2
        elif pair == '--':
            line_comment = True
            out.extend('  ')
            index += 2
        elif char == '"':
            quoted = True
            out.append(' ')
            index += 1
        else:
            out.append(char)
            index += 1
    assert depth == 0 and not quoted
    return ''.join(out)

def declarations(source, module):
    source = clean(source)
    result = []
    namespaces = []
    lines = source.splitlines()
    for line_number, line in enumerate(lines, 1):
        match = re.match(r'^namespace\s+(\S+)\s*$', line)
        if match:
            name = match.group(1)
            namespaces.append(name if not namespaces else namespaces[-1] + '.' + name)
            continue
        if re.match(r'^end(?:\s+\S+)?\s*$', line):
            if namespaces:
                namespaces.pop()
            continue
        match = re.match(r'^(?:(?:private|protected|noncomputable|unsafe|partial)\s+)*(def|abbrev|theorem|lemma|structure|inductive|class|instance)\s+([^\s({:\[]+)', line)
        if match:
            kind, name = match.groups()
            if name.startswith('_root_.'):
                full_name = name[len('_root_.'):]
            else:
                full_name = '.'.join(namespaces[-1:] + [name])
            result.append({'module': module, 'name': full_name, 'kind': kind, 'line': line_number})
        if line.startswith('attribute [simps '):
            attribute = line
            next_line = line_number
            while ']' not in attribute:
                attribute += ' ' + lines[next_line]
                next_line += 1
            if not attribute.split(']', 1)[1].strip():
                attribute += ' ' + lines[next_line]
            match = re.match(r'attribute \[simps \(config := \{ isSimp := false \}\)\s+([^\]]+)\]\s+(\S+)', attribute)
            assert match, attribute
            fields, parent = match.groups()
            for field in fields.split():
                full_name = '.'.join(namespaces[-1:] + [parent + '_' + field])
                result.append({'module': module, 'name': full_name, 'kind': 'generated_theorem_simps', 'line': line_number})
    return result

inventory = []
for path in paths:
    if not path.endswith('.lean'):
        continue
    module = path[:-5].replace('/', '.')
    source = subprocess.check_output(['git', 'show', commit + ':' + path], cwd=repo, text=True)
    old = subprocess.run(['git', 'show', base + ':' + path], cwd=repo, text=True, stdout=subprocess.PIPE, stderr=subprocess.DEVNULL)
    old_names = {item['name'] for item in declarations(old.stdout, module)} if old.returncode == 0 else set()
    inventory.extend(item for item in declarations(source, module) if item['name'] not in old_names)
assert len({(item['module'], item['name']) for item in inventory}) == len(inventory)
output = {
    'base': base,
    'commit': commit,
    'method': 'Explicit top-level source declarations plus named reader theorems generated by source simps attributes, differenced against the issue base; nested Lean comments and strings excluded. Compiler-generated auxiliary constants are covered separately by the stored-constant/axiom collector.',
    'count': len(inventory),
    'counts_by_kind': dict(collections.Counter(item['kind'] for item in inventory)),
    'counts_by_module': dict(collections.Counter(item['module'] for item in inventory)),
    'declarations': inventory,
}
path = pathlib.Path('/private/tmp/hash-sign-fill/final-source-declarations.json')
path.write_text(json.dumps(output, indent=2) + '\n')
print(json.dumps({key: value for key, value in output.items() if key != 'declarations'}, indent=2))
