"""census_md.py <census-reads.txt> <ReaderLookup.log> <staging census.txt> <out.md> (gsw-6b-statements, sub-agent
probe; new; check 6). Writes the reader census: for every foreign definition read (census6b.py), its declaration
`path:line` at the statement head, its published readers (`path:line`, flagged [admitted] when the reader's own
proof is still `sorry`), who reads it (A body / B target statement / C target sketch / C2 sketch cites a reader),
and its staging-census entry (confirmed, line corrected, or added). Readers are ranked: `_eq`, `_iff`, `_def`,
`_apply`, `_fst`/`_snd`/simps projections and case readers first."""
import sys, re, collections
reads_f, look_f, stage_f, out = sys.argv[1:5]
FALSE_POS = {'Complexity.P': 'sketch variable `P` resolved through `open Complexity` (not read)',
             'TCSlib.Cryptography.AdvancedEncryption.Homomorphic.GSW.eval':
                 'G10 sketch names phase-5 `eval_encrypts` as a model ("as `eval_encrypts` does"); `eval` not read'}
reads = {}
for l in open(reads_f):
    if l.startswith('READ\t'):
        _, d, w = l.rstrip('\n').split('\t'); reads[d] = w.split()
look = {}
for l in open(look_f):
    if l.startswith('READERS\t'):
        _, d, loc, rs = l.rstrip('\n').split('\t'); look[d] = (loc, rs)
stage = {}
for l in open(stage_f):
    p = l.rstrip('\n').split('\t')
    if len(p) == 3: stage[p[0]] = (p[1], p[2])
def path(loc):
    m, ln = loc.rsplit(':', 1)
    return m.replace('.', '/') + '.lean:' + ln
def rank(r):
    n = r.split('@')[0].split('.')[-1]
    for i, suf in enumerate(['_eq', '_iff', '_def', '_apply', '_fst', '_snd', '_lwe', '_width']):
        if n.endswith(suf): return (0, i, n)
    if '[admitted]' in r: return (2, 0, n)
    return (1, 0, n)
def short(d): return d.replace('TCSlib.Cryptography.AdvancedEncryption.Homomorphic.', '').replace('TCSlib.Cryptography.', '')
rows = []; missing = []
for d in sorted(reads):
    if d in FALSE_POS: continue
    loc, rs = look[d]
    who = sorted({w.split(':')[0] for w in reads[d]})
    whos = ', '.join(sorted({':'.join(w.split(':')[2:3]) for w in reads[d]}))
    if rs == 'MISSING':
        readers = 'MISSING'; missing.append(d)
    else:
        lst = sorted(rs.split(), key=rank)
        readers = '; '.join(f'`{x.split("@")[0].split(".")[-1]}` {path(x.split("@")[1]).replace("[admitted]", "")}'
                            + (' [admitted]' if '[admitted]' in x else '') for x in lst[:4])
        if len(lst) > 4: readers += f'; … {len(lst) - 4} more'
    sk = d.split('.')[-1]
    st = [k for k in stage if k == sk or k.endswith('.' + sk) or sk.endswith('.' + k)]
    st = [k for k in st if path(loc).split(':')[0] in stage[k][0]]
    if st:
        sline = stage[st[0]][0]; status = 'confirmed' if sline.split(':')[-1].split(',')[0] == path(loc).split(':')[1] or path(loc).split(':')[1] in sline.split(':')[-1].split(',') else f'line corrected (staging {sline.split(":")[-1]})'
    else: status = 'added'
    rows.append((short(d), path(loc), readers, '/'.join(who), whos, status))
with open(out, 'w') as o:
    o.write('# Reader census (check 6, G6A-F03), gsw-6b statements at a855e111f3dd31e1d4664117618813dff544cb6d\n\n')
    o.write('Generated by `tools/probe/census_md.py` from `CensusDump.log` (Lean: foreign TCSlib constants in every\n'
            'new definition body and target statement), `SketchResolve.log` (Lean: every backticked identifier of\n'
            'every target `**Proof sketch.**`, resolved in the files\' namespace and opens) and `ReaderLookup.log`\n'
            '(Lean: every TCSlib theorem named `<def>_…` whose statement mentions the definition). Lines are\n'
            'declaration-name lines at the statement head. *Read by*: A = a new definition\'s body, B = a target\'s\n'
            'statement, C = a target\'s sketch names it, C2 = a target\'s sketch cites one of its readers.\n'
            'Reducible abbreviations, projections, structure types and instances are notation (listed at the end).\n\n')
    o.write(f'**MISSING: {len(missing)}** — ' + ', '.join(f'`{short(m)}`' for m in missing) + '.\n\n')
    o.write('| definition | declared | published readers (first 4, ranked) | read by | readers in | staging census |\n')
    o.write('|---|---|---|---|---|---|\n')
    for r in rows: o.write('| `' + r[0] + '` | ' + ' | '.join(r[1:]) + ' |\n')
    o.write('\n## Excluded false positives of the automatic collection\n\n')
    for k, v in FALSE_POS.items(): o.write(f'* `{short(k)}`: {v}.\n')
    o.write('\n## Staging-census entries not met by the automatic collection\n\n')
    met = {r[0].split('.')[-1] for r in rows}
    for k, (loc, rd) in stage.items():
        if k.split('.')[-1] not in met: o.write(f'* `{k}` ({loc}): staging readers {rd}\n')
print(f'{len(rows)} definitions, MISSING {len(missing)}: {missing}')
