"""declnames.py <repo> <rev> <outfile> (gsw-6b-statements, sub-agent probe; adapted from the 6a statement job's
evidence/tools/xr/touched.py `decls` cutter and evidence/tools/clash_scan.py). Changes: reads every `.lean` file under
TCSlib/, TCSlib.lean and audits/ at <rev> from git objects (one `git cat-file --batch` pass); resolves full names
through `namespace`/`end` (and `_root_.`); besides the declarations of the keyword cutter it adds structure/class
fields (`S.f`), inductive constructors (`I.c`), `structure`'s `S.mk` and the names generated by `@[simps ... p q]`
(`n_p`, `n_q`) when the projections are listed. Private declarations are kept (flagged). Output TSV:
full name, short name, kind, private, path:line."""
import re, subprocess, sys
repo, rev, out = sys.argv[1:4]
files = [f for f in subprocess.run(['git', '-C', repo, 'ls-tree', '-r', '--name-only', rev, '--', 'TCSlib',
         'TCSlib.lean', 'audits'], capture_output=True, text=True, check=True).stdout.split() if f.endswith('.lean')]
KW = r'(theorem|lemma|def|abbrev|structure|inductive|instance|class|opaque|axiom)'
DECL = re.compile(r'^(@\[[^\]]*\]\s*)*((?:private|protected|noncomputable|nonrec|partial|unsafe|scoped)\s+)*'
                  + KW + r'\b\s*([^\s(:{\[]*)')
inp = ''.join(f'{rev}:{f}\n' for f in files).encode()
raw = subprocess.run(['git', '-C', repo, 'cat-file', '--batch'], input=inp, capture_output=True, check=True).stdout
pos = 0; texts = {}
for f in files:
    nl = raw.index(b'\n', pos); hdr = raw[pos:nl].split(); size = int(hdr[2])
    texts[f] = raw[nl + 1:nl + 1 + size].decode('utf-8', 'replace'); pos = nl + 1 + size + 1
rows = []
for f, src in texts.items():
    lines = src.split('\n'); depth = 0; ns = []; cur = None; attr = ''
    for i, l in enumerate(lines):
        incom = depth > 0
        j = 0
        while j < len(l):
            if l.startswith('/-', j): depth += 1; j += 2
            elif l.startswith('-/', j) and depth: depth -= 1; j += 2
            elif l.startswith('--', j) and depth == 0: break
            else: j += 1
        if incom: continue
        m = re.match(r'^namespace\s+(\S+)', l)
        if m: ns.append(m.group(1)); cur = None; continue
        m = re.match(r'^end(\s+(\S+))?\s*$', l)
        if m:
            if m.group(2) and ns and (ns[-1] == m.group(2) or ns[-1].endswith('.' + m.group(2))): ns.pop()
            cur = None; continue
        if l.startswith('@['): attr = l
        m = DECL.match(l)
        if m:
            kind, name = m.group(3), m.group(4)
            fullattr = attr + ' ' + l
            attr = ''
            if not name or name.startswith('[') or name.startswith(':'):
                cur = None; continue
            priv = 'private' in (m.group(2) or '')
            full = name[7:] if name.startswith('_root_.') else '.'.join(ns + [name])
            rows.append((full, kind, priv, f'{f}:{i + 1}'))
            sm = re.search(r'simps!?\s*(?:\([^)]*\))?\s*([A-Za-z_][\w ]*)\]', fullattr)
            if sm:
                for p in sm.group(1).split():
                    rows.append((f'{full}_{p}', 'simps', priv, f'{f}:{i + 1}'))
            cur = (full, kind, priv) if kind in ('structure', 'class', 'inductive') else None
            if kind in ('structure', 'class'): rows.append((full + '.mk', 'ctor', priv, f'{f}:{i + 1}'))
            continue
        if l and not l[0].isspace(): cur = None
        if cur:
            fm = re.match(r'^\s{2,}([A-Za-z_][\w\']*)\s*:', l)
            cm = re.match(r'^\s*\|\s*([A-Za-z_][\w\']*)', l)
            if cur[1] in ('structure', 'class') and fm and fm.group(1) not in ('where', 'extends'):
                rows.append((cur[0] + '.' + fm.group(1), 'field', cur[2], f'{f}:{i + 1}'))
            if cur[1] == 'inductive' and cm:
                rows.append((cur[0] + '.' + cm.group(1), 'ctor', cur[2], f'{f}:{i + 1}'))
with open(out, 'w') as o:
    o.write(f'# declnames.py {repo} {rev}: {len(files)} files, {len(rows)} names\n')
    for full, kind, priv, loc in rows:
        o.write(f'{full}\t{full.split(".")[-1]}\t{kind}\t{"private" if priv else "public"}\t{loc}\n')
print(f'{rev}: {len(files)} files, {len(rows)} names -> {out}')
