"""mk_p3.py (gsw-6b-statements, sub-agent probe; new): write probe P3 (O2,
`decode_iff_mem_Ico`) to /home/user/ev/probes/P3_DecodeInterval.lean: one theorem per modulus
2 <= q <= 63, the statement of `decode_iff_mem_Ico` at the concrete `LWE.Parameters`
`<1, 1, q>` for every residue, proved by `decide` (the proof term is kernel-checked), then
`#print axioms` of each, a negative control (a wrong upper end `≤`, expected to fail, kept in
a separate file P3x_Control.lean), and `#eval` of the mismatch count for 64 <= q <= 2000."""
import sys
out = '/home/user/ev/probes/P3_DecodeInterval.lean'
L = []
L.append('import TCSlib.Cryptography.LWE.BitEncoding\n')
L.append('/-! Probe P3 (gsw-6b statements, O2): `decode_iff_mem_Ico` at `LWE.Parameters` '
         '`⟨1, 1, q, _⟩`,\nfor every residue `v`, by `decide` for every `2 ≤ q ≤ 63`; '
         '`#eval` mismatch counts for\n`64 ≤ q ≤ 2000` (evidence, not proof). Generated by '
         'tools/probe/mk_p3.py. -/\n')
L.append('open TCSlib.Cryptography.LWE TCSlib.Cryptography.LWE.BitEncoding\n')
L.append('namespace P3\n')
L.append('/-- The toy LWE parameters with modulus `q`. -/')
L.append('abbrev LP (q : ℕ) (h : 2 ≤ q) : Parameters := ⟨1, 1, q, h⟩\n')
for q in range(2, 64):
    L.append(f'theorem o2_q{q} : ∀ v : ZMod (LP {q} (by decide)).modulus,\n'
             f'    decode (LP {q} (by decide)) v = true ↔\n'
             f'      decodeLo (LP {q} (by decide)) ≤ v.val ∧ v.val < decodeHi (LP {q} (by decide)) '
             f':= by\n  decide\n')
L.append('/-- Mismatches of the interval test against `decode`, over every residue of `q`. -/')
L.append('def mismatches (q : ℕ) (h : 2 ≤ q) : ℕ :=\n'
         '  ((List.range q).filter fun a =>\n'
         '    decode (LP q h) (a : ZMod q) !=\n'
         '      decide (decodeLo (LP q h) ≤ (a : ZMod q).val ∧ '
         '(a : ZMod q).val < decodeHi (LP q h))).length\n')
L.append('/-- Total mismatches over `lo ≤ q ≤ hi`, and the number of moduli checked. -/')
L.append('def sweep (lo hi : ℕ) : ℕ × ℕ :=\n'
         '  (List.range (hi + 1 - lo)).foldl (fun acc i =>\n'
         '    let q := lo + i\n'
         '    if h : 2 ≤ q then (acc.1 + mismatches q h, acc.2 + 1) else acc) (0, 0)\n')
L.append('end P3\n')
for q in range(2, 64):
    L.append(f'#print axioms P3.o2_q{q}')
L.append('')
L.append('-- (total mismatches, moduli checked) over 64 ≤ q ≤ 2000')
L.append('#eval P3.sweep 64 2000')
L.append('-- the same sweep over 2 ≤ q ≤ 63 (agrees with the decide block)')
L.append('#eval P3.sweep 2 63')
open(out, 'w').write('\n'.join(L) + '\n')
ctl = '/home/user/ev/probes/P3x_Control.lean'
open(ctl, 'w').write('''import TCSlib.Cryptography.LWE.BitEncoding
/-! Probe P3x (negative control for P3): the interval with a wrong upper end (`≤ decodeHi`) or a
wrong lower end (`decodeLo - 1 ≤`) must be refuted by `decide` at q = 63 and q = 8; expected:
exactly 4 errors "decide proved that the proposition ... is false". -/
open TCSlib.Cryptography.LWE TCSlib.Cryptography.LWE.BitEncoding
abbrev LP (q : ℕ) (h : 2 ≤ q) : Parameters := ⟨1, 1, q, h⟩
theorem bad_hi_63 : ∀ v : ZMod (LP 63 (by decide)).modulus, decode (LP 63 (by decide)) v = true ↔
    decodeLo (LP 63 (by decide)) ≤ v.val ∧ v.val ≤ decodeHi (LP 63 (by decide)) := by decide
theorem bad_lo_63 : ∀ v : ZMod (LP 63 (by decide)).modulus, decode (LP 63 (by decide)) v = true ↔
    decodeLo (LP 63 (by decide)) - 1 ≤ v.val ∧ v.val < decodeHi (LP 63 (by decide)) := by decide
theorem bad_hi_8 : ∀ v : ZMod (LP 8 (by decide)).modulus, decode (LP 8 (by decide)) v = true ↔
    decodeLo (LP 8 (by decide)) ≤ v.val ∧ v.val ≤ decodeHi (LP 8 (by decide)) := by decide
theorem bad_lo_8 : ∀ v : ZMod (LP 8 (by decide)).modulus, decode (LP 8 (by decide)) v = true ↔
    decodeLo (LP 8 (by decide)) - 1 ≤ v.val ∧ v.val < decodeHi (LP 8 (by decide)) := by decide
''')
print('wrote', out, ctl)
