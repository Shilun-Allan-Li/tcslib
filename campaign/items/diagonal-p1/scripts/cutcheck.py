"""Cut-check files for Diagonal Part 1's direct importers (read-only; standard library only).

Usage: python3 -I cutcheck.py <base root> <landed root> <chains.txt> <out dir>

The olean snapshot holds the base `Diagonal`, so an importer cannot be elaborated against the
landed text by importing it. For each direct importer `I`, with chain `Diagonal, …, I` (the
modules of Diagonal's downstream closure that `I` imports transitively, `graph.py`), this
writes `<out dir>/<I>.cut.lean`: the union of the chain's imports minus the chain modules, then
each chain module's body (everything after its import header) in order, each inside
`section`/`end`, `Diagonal`'s from the landed root and every other from the base root. It also
writes `<out dir>/<I>.base.lean`, a copy of `I`'s base file, for the baseline elaboration
against the snapshot. To both it appends `#print axioms` for every public declaration of `I`.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
from decls import parse  # noqa: E402

TARGET = "TCSlib.Complexity.TimeHierarchy.Diagonal"


def split_header(src):
    """(imports, body): the header's `import` modules and the text after the last of them."""
    k, n, imps, end = 0, len(src), [], 0
    while k < n:
        if src[k].isspace():
            k += 1
        elif src.startswith("/-", k):
            depth, k = 1, k + 2
            while k < n and depth:
                if src.startswith("/-", k):
                    depth, k = depth + 1, k + 2
                elif src.startswith("-/", k):
                    depth, k = depth - 1, k + 2
                else:
                    k += 1
        elif src.startswith("--", k):
            e = src.find("\n", k)
            k = n if e < 0 else e
        elif src.startswith("import ", k):
            e = src.find("\n", k)
            e = n if e < 0 else e
            imps.extend(src[k + 7:e].split("--")[0].split())
            k = end = e
        else:
            break
    return imps, src[end:]


def path_of(root, mod):
    return os.path.join(root, *mod.split(".")) + ".lean"


def prints(src):
    names = [d["name"] for d in parse(src) if not d["private"]
             and d["kind"] in ("theorem", "lemma", "def", "abbrev", "structure", "instance")]
    return "".join(f"\n#print axioms {n}" for n in names) + "\n", len(names)


def main():
    base, landed, chains, out = sys.argv[1:5]
    os.makedirs(out, exist_ok=True)
    for line in open(chains, encoding="utf-8"):
        imp, chain = line.split(":", 1)
        imp, chain = imp.strip(), chain.split()
        assert chain[0] == TARGET and chain[-1] == imp, line
        union, bodies = [], []
        for m in chain:
            root = landed if m == TARGET else base
            src = open(path_of(root, m), encoding="utf-8").read()
            imps, body = split_header(src)
            for i in imps:
                if i not in chain and i not in union:
                    union.append(i)
            origin = "landed tree" if m == TARGET else "base"
            bodies.append(f"\n-- ════ body of {m} ({origin}) ════\nsection\n{body.strip()}\n"
                          f"\nend\n")
        isrc = open(path_of(base, imp), encoding="utf-8").read()
        pr, npr = prints(isrc)
        cut = (f"-- Cut check (generated by cutcheck.py): {imp} against the landed Diagonal.lean.\n"
               + "".join(f"import {i}\n" for i in union) + "".join(bodies)
               + f"\n-- ════ axioms of {imp}'s public declarations ({npr}) ════" + pr)
        short = imp.replace("TCSlib.Complexity.", "")
        open(os.path.join(out, f"{short}.cut.lean"), "w", encoding="utf-8").write(cut)
        open(os.path.join(out, f"{short}.base.lean"), "w", encoding="utf-8").write(
            isrc.rstrip("\n") + f"\n\n-- ════ axioms of {imp}'s public declarations ({npr}) ════"
            + pr)
        print(f"{short}: chain {len(chain)} module(s), {len(union)} imports, {npr} axiom prints")


if __name__ == "__main__":
    main()
