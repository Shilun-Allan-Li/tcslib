"""Print the pack's appendix: every new declaration of the landed Diagonal.lean, and every
received declaration whose docstring changed, with its docstring and head exactly as landed
(read-only; standard library only).

Usage: python3 -I appendix.py <base Diagonal.lean> <landed Diagonal.lean>
"""
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
from decls import parse  # noqa: E402

base = parse(open(sys.argv[1], encoding="utf-8").read())
land = parse(open(sys.argv[2], encoding="utf-8").read())
bmap = {d["name"]: d for d in base}
print("## Appendix A. The new declarations, as landed (docstring and statement; generated by "
      "`scripts/appendix.py`)\n")
for d in land:
    if d["name"] in bmap:
        continue
    text = d["head"] if d["kind"] not in ("structure",) else d["text"]
    print(f"### `{d['name']}` ({d['kind']}, line {d['line']})\n")
    print("```lean\n" + d["doc"] + "\n" + text.rstrip() + "\n```\n")
print("## Appendix B. Received declarations whose docstring or proof changed (statement "
      "byte-identical; docstring and new proof as landed)\n")
for d in land:
    b = bmap.get(d["name"])
    if b is None or (b["doc"] == d["doc"] and b["body"] == d["body"]):
        continue
    print(f"### `{d['name']}` ({d['kind']}, line {d['line']})\n")
    print("```lean\n" + d["doc"] + "\n" + d["text"].rstrip() + "\n```\n")
