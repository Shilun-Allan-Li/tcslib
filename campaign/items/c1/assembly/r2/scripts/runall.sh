summ "$out" "$ex"; echo '```'; san <<<"$out"; echo '```'
ok0 "$ex" "$out"; check "axioms probe elaborates" $?
sa=$(grep "sorryAx" <<<"$out" | sed -E "s/^'([^']*)'.*/\1/" | sort | tr '\n' ' ')
echo "Declarations with \`sorryAx\`: $sa"
[ "$sa" = "Turing.guessRunTM_accepts_iff Turing.guessRunTM_haltsWithin Turing.guessRunTM_runWith Turing.guessRunTM_runWith_handoff Turing.guessRunTM_runWith_handoff_state Turing.guessRunTM_runWith_live Turing.guessRunTM_silent_spec Turing.ndWriterTM_run_block " ]
check "sorryAx exactly on the seven run theorems and the writer's contract" $?
echo
echo "## 2. Sorry isolation (fail-closed generation)"
echo
echo "\`isolate.py\` deletes its target first, asserts each replacement, exits 1 on any failure, and prints"
echo "\`generated <target>\` last; Lean runs on a target only after exit 0 and that line."
for f in C1Assembly AssemblyConsumerProbe; do
  g=$(gen_iso "$O/$f.lean" "$O/work/Iso$f.lean"); r=$?
  echo "* \`$f\`: builder exit $r"; echo '```'; echo "$g"; echo '```'
  if [ "$r" -eq 0 ] && grep -q "^generated " <<<"$g" && [ -f "$O/work/Iso$f.lean" ]; then
    check "isolation $f: generated" 0
    out=$(el "$O/work/Iso$f.lean"); ex=$?; summ "$out" "$ex"
    echo '```'; san <<<"$out" | tr -d '\n' | sed "s/'Turing/\n'Turing/g"; echo; echo '```'
    ok0 "$ex" "$out" && ! grep -q sorryAx <<<"$out"; check "isolation $f: no sorryAx" $?
  else
    check "isolation $f: generated" 1; echo "(not elaborated: generation failed)"
  fi
done
echo
echo "### Control: a syntax-equivalent writer argument \`(j)\` must make the builder fail, leave no target,"
echo "and stop Lean (the round-1 failure path)"
touch "$O/work/IsoCtrl.lean"   # a stale target from an earlier run must be removed by the builder
g=$(gen_iso "$O/work/ctrl_iso_unit.lean" "$O/work/IsoCtrl.lean"); r=$?
echo '```'; echo "$g" | tail -3; echo "builder exit (through the pipeline) $r; target present: $([ -e "$O/work/IsoCtrl.lean" ] && echo yes || echo no)"; echo '```'
[ "$r" -ne 0 ] && [ ! -e "$O/work/IsoCtrl.lean" ]; check "isolation control: failure propagates, stale target removed" $?
} > "$L/axioms.log"

