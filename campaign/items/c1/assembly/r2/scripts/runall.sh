#!/usr/bin/env bash
# Round 2 of the C1-A guess-then-run assembly statement gate: re-run every check, write the logs.
# Read-only on the repository: `lean` only through tools/leanelab.sh (throttled; no -o, no olean
# written), python3 -I only, no lake/elan; git only read-only (rev-parse, ls-tree, diff, archive
# to stdout, status with optional locks off). FAIL-CLOSED: `set -o pipefail`; every check records
# PASS or FAIL in <OUT>/logs/summary.txt; each generator's own status is checked before Lean runs
# on its output; the script exits 1 if any check failed.
# Usage: bash runall.sh <S>
#   WT  = <S>/wt-c1asm (read-only; supplies the Mathlib packages, manifest unchanged, and the
#         object store); TIP = the remote-tracking ref of the campaign branch (no fetch is run)
#   BASE = <OUT>/base, the tip's tree (git archive); OL = <S>/oleans-lb6 (#92's replay output)
set -o pipefail
export LC_ALL=C
S="$1"; WT="$S/wt-c1asm"; OL="$S/oleans-lb6"; O="$S/gate-c1asm/r2"; SC="$O/scripts"; L="$O/logs"
BASE="$O/base"; REF=origin/complexity/arora-barak-ch3-4
TIP=$(cd "$WT" && git rev-parse --verify "$REF^{commit}")
mkdir -p "$L" "$O/work"; : > "$L/summary.txt"; FAILS=0
el() { bash "$S/tools/leanelab.sh" "$WT" "$OL" "$1" 2>&1; }
san() { sed "s|$O/|<OUT>/|g; s|$S/|<S>/|g"; }
cnt() { grep -c -- "$1" <<<"$2"; }
summ() { # output exit
  local e w s
  e=$(cnt ': error' "$1"); w=$(cnt ': warning' "$1"); s=$(cnt "declaration uses 'sorry'" "$1")
  echo "  exit $2 | errors $e | warnings $w | of which \`declaration uses 'sorry'\` $s | other warnings $((w - s))"
}
check() { # name status(0 = pass)
  if [ "$2" -eq 0 ]; then echo "PASS $1" >> "$L/summary.txt"
  else echo "FAIL $1" >> "$L/summary.txt"; FAILS=$((FAILS + 1)); fi
}
ok0() { [ "$1" -eq 0 ] && [ "$(cnt ': error' "$2")" -eq 0 ]; }   # exit 0 and no error
warnset() { grep ': warning' <<<"$1" | sed -E 's/^[^:]*:[0-9]+:[0-9]+: //' | sort; }

rm -rf "$BASE"; mkdir -p "$BASE"
(cd "$WT" && git archive "$TIP" TCSlib lean-toolchain lake-manifest.json scripts/campaign_style_lint.py \
  audits policy.md workflow.md) | tar -x -C "$BASE"; check "base sources archived from the tip" $?
python3 -I "$SC/mkprobes.py" "$O" >/dev/null; check "probe files built" $?
rm -rf "$O/cut" "$O/landed" "$O/parts"
MKL=$(python3 -I "$SC/mklanded.py" "$BASE" "$O/C1Assembly.lean" "$O"); check "landing forms and cut files built" $?
python3 -I "$SC/mkcontrols.py" "$O" >/dev/null; check "controls built" $?
HDR="Tool: \`bash <S>/tools/leanelab.sh <S>/wt-c1asm <S>/oleans-lb6 <file>\` (direct \`lean\`, throttled, no
\`-o\`, no olean written). Campaign tip: $TIP (\`git rev-parse $REF\`). Sources: <OUT>/base, the
tip's tree (\`git archive\`, read-only). Snapshot: \`oleans-lb6\` (\`base.log\`). \`wt-c1asm\` (at
$(cd "$WT" && git rev-parse HEAD | cut -c1-8), read-only) supplies only the Mathlib packages. Toolchain: \`$(cat "$BASE/lean-toolchain")\`.
<OUT> is this round's directory; <S> the scratchpad. Run: $(date -u '+%Y-%m-%d %H:%M UTC')."
MAP="In the repository: <OUT>/C1Assembly.lean -> audits/evidence/c1/assembly/r2/C1Assembly.lean.txt;
<OUT>/<x> -> audits/evidence/c1/assembly/r2/<x> (.lean as .lean.txt); <OUT>/logs/<x>.log ->
audits/logs/c1-assembly-statements-r2-<x>.log (summary.txt -> -summary.log). <OUT>/work/ and
<OUT>/base/ are regenerated by this script and not bundled. Round 1's logs stay as committed."

