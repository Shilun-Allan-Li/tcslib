"""The pack's appendix, generated from the landed files (read-only; standard library only).

Usage: python3 -I appendix.py <base root> <landed root>
Prints, per landed file, every new declaration (docstring and statement; whole text for
definitions and structures) and every received declaration whose proof or docstring changed
(whole text), exactly as landed.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
from decls import parse  # noqa: E402

TM = "TCSlib/Complexity/TuringMachine"
FILES = [f"{TM}/UniversalK.lean", f"{TM}/Build/StepBlockLoop.lean", f"{TM}/SelfUniversal.lean",
         f"{TM}/Codes2Tape.lean"]
PROMO = {"Turing.Code2TM.serialize_eq_serializeK": "Turing.twoTape_serialize_eq"}
base_root, land_root = sys.argv[1:3]
print("## Appendix: the statements as landed (generated by `scripts/appendix.py`)\n")
for rel in FILES:
    land = parse(open(os.path.join(land_root, rel), encoding="utf-8").read())
    bp = os.path.join(base_root, rel)
    base = {d["name"]: d for d in parse(open(bp, encoding="utf-8").read())} \
        if os.path.isfile(bp) else {}
    shown = []
    for d in land:
        b = base.get(PROMO.get(d["name"], d["name"]))
        if b is not None and b["doc"] == d["doc"] and b["body"] == d["body"] \
                and d["name"] not in PROMO:
            continue
        shown.append(d)
    if not shown:
        continue
    print(f"### `{rel}`\n")
    for d in shown:
        b = base.get(PROMO.get(d["name"], d["name"]))
        tag = "new" if b is None else ("promoted" if d["name"] in PROMO else "received, body changed")
        whole = d["kind"] in ("def", "structure", "abbrev") or tag != "new"
        text = d["text"] if whole else d["head"]
        print(f"#### `{d['name']}` ({d['kind']}, {tag}, line {d['line']})\n")
        print("```lean\n" + d["doc"] + "\n" + text.rstrip() + ("" if whole else " := by\n  sorry"
              if "sorry" in d["body"] else " := …") + "\n```\n")
