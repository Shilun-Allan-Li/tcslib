"""Make A1ConsumerProbe.lean from the drafter's SCPRouteProbe record: A1's lemmas under their final
names, namespaces and binders (as in the review's a1.patch), proved before the seal; the
copying-state lemma specialized to the two published instances; the SCP route re-run with the
final names and with the dominance step citing the published `Complexity.logSpace_le_succ` (no
`logSpace_eq`); and E-Q's witness step through the final `Complexity.timeConstructible_iff`.
Every replacement is asserted to occur exactly the expected number of times.
Usage: mkconsumer.py <SCPRouteProbe.lean.txt> <out.lean>"""
import sys
src, out = sys.argv[1], sys.argv[2]
t = open(src, encoding="utf-8").read()

def rep(t, a, b, n=1):
    assert t.count(a) == n, (t.count(a), a[:70])
    return t.replace(a, b)

# header and imports
i, j = t.index("/-\n"), t.index("-/\n") + 3
t = t[:i] + """/-
Review of megafill D (2026-10-24): A1 as it would land, consumed. Generated by
`scripts/mkconsumer.py` from the drafting agent's `SCPRouteProbe.lean.txt`. A probe, not library
code: the A1 lemmas are declared here under their final names because the snapshot has none.
-/
""" + t[j:]
t = rep(t, "import TCSlib.Complexity.ClassNP.Transducer\n", """import TCSlib.Complexity.ClassNP.Transducer
import TCSlib.Complexity.Diagonalization.NTimeDiagonalizer
import TCSlib.Complexity.CircuitComplexity.MeyerVerifierGlue
""")
# the stand-ins become A1's final declarations, outside `namespace Complexity`
a = t.index("namespace Complexity\n\nopen Turing\n\n/-! ### Stand-ins")
b = t.index("/-! ### The sealed route -/")
a1 = '''/-! ### A1, final names (proved before the seal, as in their home files) -/

namespace Complexity

open Turing

theorem timeConstructible_iff (T : ℕ → ℕ) :
    TimeConstructible T ↔
      (∀ n, n ≤ T n) ∧ ∃ c : ℕ, 0 < c ∧ ∃ M : FinTM Bool, ∀ x : List Bool,
        M.ComputesInTime x (T x.length).bits (c * (T x.length + 1)) :=
  Iff.rfl

theorem spaceConstructible_iff (S : ℕ → ℕ) :
    SpaceConstructible S ↔
      (∀ n, logSpace n ≤ S n) ∧ ∃ c : ℕ, 0 < c ∧ ∃ M : FinTM Bool,
        M.ComputesInSpace (fun x => (S x.length).bits) fun n => c * S n :=
  Iff.rfl

theorem logSpace_eq (n : ℕ) : logSpace n = Nat.log 2 n + 1 := rfl

section
variable {σ : Type}

theorem transduce_nil (δ : σ → Bool → σ) (o : σ → Bool → Option Bool) (q : σ) :
    transduce δ o q [] = [] := rfl

theorem transduce_cons (δ : σ → Bool → σ) (o : σ → Bool → Option Bool) (q : σ) (b : Bool)
    (l : List Bool) :
    transduce δ o q (b :: l) = (o q b).toList ++ transduce δ o (δ q b) l := rfl

theorem transduce_of_copy (δ : σ → Bool → σ) (o : σ → Bool → Option Bool) (q : σ)
    (hδ : ∀ b, δ q b = q) (ho : ∀ b, o q b = some b) (l : List Bool) :
    transduce δ o q l = l := by
  induction l with
  | nil => exact transduce_nil δ o q
  | cons b l ih =>
    rw [transduce_cons, hδ, ho, ih]
    rfl
end

end Complexity

namespace Turing.FinTM

theorem computesInSpace_iff (M : FinTM Bool) (f : List Bool → List Bool) (s : ℕ → ℕ) :
    M.ComputesInSpace f s ↔
      ∀ x : List Bool, ∃ t, M.ComputesInTime x (f x) t ∧
        M.tm.spaceUsed (M.tm.initCfg x) t ≤ s x.length :=
  Iff.rfl

end Turing.FinTM

/-! ### The copying-state lemma specializes to both published instances -/

/-- `Complexity.KarpLipton.transduce_drop_true`'s statement, from the general lemma. -/
example (p : List Bool) :
    Complexity.transduce Complexity.KarpLipton.dropTr Complexity.KarpLipton.dropOut true p = p :=
  Complexity.transduce_of_copy _ _ true (fun _ => rfl) (fun _ => rfl) p

/-- `Complexity.Meyer.transduce_fT_copy`'s statement, from the general lemma. -/
example (u : List Bool) : Complexity.transduce Complexity.Meyer.fTδ Complexity.Meyer.fTo none u = u :=
  Complexity.transduce_of_copy _ _ none (fun _ => rfl) (fun _ => rfl) u

/-- The two published statements are the instances (their types agree with the above). -/
example : (∀ p : List Bool, Complexity.transduce Complexity.KarpLipton.dropTr
    Complexity.KarpLipton.dropOut true p = p) ∧
    ∀ u : List Bool, Complexity.transduce Complexity.Meyer.fTδ Complexity.Meyer.fTo none u = u :=
  ⟨Complexity.KarpLipton.transduce_drop_true, Complexity.Meyer.transduce_fT_copy⟩

namespace Complexity

open Turing

'''
t = t[:a] + a1 + t[b:]
t = rep(t, "attribute [local irreducible] Complexity.SpaceConstructible",
        "attribute [local irreducible] Complexity.TimeConstructible Complexity.SpaceConstructible")
t = rep(t, "scp_transduce_of_copy _ _ true", "transduce_of_copy _ _ true")
t = rep(t, "exact scp_transduce_nil _ _ _", "exact transduce_nil _ _ _")
t = rep(t, "rw [scp_transduce_cons]", "rw [transduce_cons]")
t = rep(t, "(scp_spaceConstructible_iff _).mpr", "(spaceConstructible_iff _).mpr")
t = rep(t, "(scp_computesInSpace_iff _ _ _).mpr", "(FinTM.computesInSpace_iff _ _ _).mpr")
t = rep(t, """  · rw [scp_logSpace_eq]
    have h1 : Nat.log 2 n ≤ n := Nat.log_le_self 2 n
""", """  · have h1 := logSpace_le_succ n
""")
t = rep(t, "theorem scp_route", "theorem a1c_scp_route")
t = rep(t, "#print axioms Complexity.scp_route", "#print axioms Complexity.a1c_scp_route")
t = rep(t, "end Sealed\n\nend Complexity\n", """/-- E-Q's witness step through the final `Complexity.timeConstructible_iff`. -/
theorem a1c_eq_witness {f : ℕ → ℕ} (hf : TimeConstructible f) :
    (∀ n, n ≤ f n) ∧ ∃ c : ℕ, 0 < c ∧ ∃ M : FinTM Bool, ∀ x : List Bool,
      M.ComputesInTime x (f x.length).bits (c * (f x.length + 1)) :=
  (timeConstructible_iff f).mp hf

end Sealed

end Complexity
""")
t += "#print axioms Complexity.a1c_eq_witness\n"
assert "scp_logSpace_eq" not in t and "scp_spaceConstructible_iff" not in t
assert "scp_computesInSpace_iff" not in t and "scp_transduce_nil" not in t
open(out, "w", encoding="utf-8").write(t)
print("wrote", out)
