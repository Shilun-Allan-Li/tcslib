"""Markdown tables of the round-3 ledger (evidence file ledger-r3-tables.md), from the work files
written by run_r3.zsh. usage: python3 -I tables3.py <workdir> <out.md>"""
import json, os, sys
wk, dst = sys.argv[1:3]
rd = lambda f: [c for c in (l.rstrip('\n').split('\t') for l in open(os.path.join(wk, f), encoding='utf-8')) if c and c[0] not in ('pid', 'row', 'path')]
PB = {c[0]: c for c in rd('pairs3-base.tsv')}; PL = {c[0]: c for c in rd('pairs3-landed.tsv')}
CB = {c[0]: c for c in rd('classify3-base.tsv')}; CL = {c[0]: c for c in rd('classify3-landed.tsv')}
TR = rd('transitions.tsv'); DI = rd('dispositions.tsv')
JB = json.load(open(os.path.join(wk, 'ledger3-base.json'))); JL = json.load(open(os.path.join(wk, 'ledger3-landed.json')))
DB = rd('ledger3-base-decls.tsv'); DL = rd('ledger3-landed-decls.tsv')
sh = lambda p: p.replace('TCSlib/Complexity/', '')
o = open(dst, 'w', encoding='utf-8'); w = lambda s='': o.write(s + '\n')
w('# ARM fill gate, round 3: the ledger re-measured on the payback tree (tables)')
w()
w('Generated by `scripts/tables3.py`. Every count is MEASURED by the scripts named in `NOTES.md` '
  '(copy-text screen v3, unmodified, over the 218-file population at the base, at the landed '
  'tree and at the tip); classes, groups and factorings are the pack author\'s, carried from round 2 except where '
  'the basis column names a round-3 change. Lines are at the tree named in each table.')
w()
w('Groups: **P1** the payback PR (decided); **P1+** rows added to the payback by the user in round 2; '
  '**A2a** ARM-2 (a); **A2b** ARM-2 (b); **A2w** ARM-2 and the user\'s dedup window (G-rep); **X** not real duplication.')
w()
w('## 1. Pair inventory and transitions (base → landed)')
w()
cnt = {}
for c in TR: cnt.setdefault(c[1], {}).setdefault(c[4], 0); cnt[c[1]][c[4]] += 1
w('| Category | Base pairs | Landed pairs | Present at both | Removed by the payback | New at the landed tree |')
w('|---|---:|---:|---:|---:|---:|')
for cat in ('lib', 'internal', 'same'):
    b = sum(1 for c in PB.values() if c[1] == cat); l = sum(1 for c in PL.values() if c[1] == cat); d = cnt.get(cat, {})
    w(f"| {cat} | {b} | {l} | {d.get('present', 0)} | {d.get('removed', 0)} | {d.get('new-at-landed', 0)} |")
w(f"| **total** | **{len(PB)}** | **{len(PL)}** | **{sum(v.get('present', 0) for v in cnt.values())}** | **{sum(v.get('removed', 0) for v in cnt.values())}** | **{sum(v.get('new-at-landed', 0) for v in cnt.values())}** |")
w()
w('### Removed pairs (present at the base, absent at the landed tree), with their base class and group')
w()
w('| Pair | A | B | Base class | Base group | Base shared |')
w('|---|---|---|---|---|---:|')
for c in TR:
    if c[4] == 'removed': w(f'| {c[0]} | `{sh(c[2])}` | `{sh(c[3])}` | {c[5]} | {c[6]} | {c[7]} |')
w()
w('### New pairs at the landed tree')
w()
w('| Pair | A | B | Landed class | Group | Shared |')
w('|---|---|---|---|---|---:|')
for c in TR:
    if c[4] == 'new-at-landed': w(f'| {c[0]} | `{sh(c[2])}` | `{sh(c[3])}` | {c[8]} | {c[9]} | {c[10]} |')
w()
w('### Pairs new since round 2 already at the base (code changed since the received tree)')
w()
w('| Pair | Cat | A (base lines) | B (base lines) | Shared | Class | Group | Basis |')
w('|---|---|---|---|---:|---|---|---|')
for i, c in PB.items():
    if c[14] == 'no':
        k = CB[i]; w(f'| {i} | {c[1]} | `{sh(c[2])}:{c[4]}` `{c[3]}` | `{sh(c[7])}:{c[9]}` `{c[8]}` | {c[13]} | {k[2]} | {k[4]} | {k[5]} |')
w()
w('## 2. The payback ledger rows (34 P1/P1+ pairs, L049, the four manual rows): disposition and screen verdict')
w()
w('| Row | Group, family | Copy | Copy action (ledger map) | Original | Original action | Shared declaration after | Base screen | Landed screen |')
w('|---|---|---|---|---|---|---|---|---|')
for c in DI: w('| ' + ' | '.join(c) + ' |')
w()
w('## 3. Round-3 classification changes')
w()
w('| Pair | A | B | Round-2 class/group | Round-3 class/group | Basis |')
w('|---|---|---|---|---|---|')
r2 = {c[0]: c for c in (l.rstrip('\n').split('\t') for l in open(os.path.join(wk, 'r2', 'classify.tsv'), encoding='utf-8')) if c[0] != 'pid'}
for i in ('L066', 'L049', 'S072', 'S073', 'S074', 'I082', 'I083', 'L033', 'L119', 'L120'):
    c = PB.get(i) or PL.get(i); k = CB.get(i) or CL.get(i)
    w(f'| {i} | `{sh(c[2])}` `{c[3]}` | `{sh(c[7])}` `{c[8]}` | {r2[i][2]}/{r2[i][4]} | {k[2]}/{k[4]} | {k[5]} |')
w()
def totals(J, title):
    D = J['denominators']; T = J['totals']
    w(f'### {title}')
    w()
    w(f"Denominators: {D['code']:,} code lines; {D['elig']:,} screen-eligible body characters (declarations with a body of at least 60 whitespace-free characters); {D['all']:,} body characters in all.")
    w()
    w('| Accounting | Declarations | Whole body: code lines | Whole body: chars (/eligible; /all) | Shared text: chars (/eligible; /all) | Shared text: code lines |')
    w('|---|---:|---:|---:|---:|---:|')
    for k, name in (('C', 'C, every candidate'), ('K', 'K, classified, N excluded'), ('K+', 'K+, with the manual rows')):
        t = T[k]
        w(f"| {name} | {t['n']} | {t['wl']:,} ({t['wl']/D['code']:.1%}) | {t['wc']:,} ({t['wc']/D['elig']:.1%}; {t['wc']/D['all']:.1%}) | {t['sc']:,} ({t['sc']/D['elig']:.1%}; {t['sc']/D['all']:.1%}) | {t['sl']:,.0f} ({t['sl']/D['code']:.1%}) |")
    w()
w('## 4. Ledger totals')
w()
totals(JB, 'At the base (the merged tip; before the payback)')
totals(JL, 'At the landed tree (after the payback)')
def bygroup(DD, title):
    w(f'### K+ by group: {title}')
    w()
    w('| Group | Declarations | Code lines | Body chars | Shared chars |')
    w('|---|---:|---:|---:|---:|')
    g = {}
    for d in DD: g.setdefault(d[7], []).append(d)
    for k in ('P1', 'P1+', 'A2a', 'A2w', 'A2b'):
        v = g.get(k, [])
        w(f"| {k} | {len(v)} | {sum(int(x[3]) for x in v):,} | {sum(int(x[4]) for x in v):,} | {sum(int(x[5]) for x in v):,} |")
    w()
bygroup(DB, 'base'); bygroup(DL, 'landed')
MEAS = [('wce', 'whole body, chars / screen-eligible'), ('wca', 'whole body, chars / all body'), ('wl_', 'whole body, code lines'),
        ('sce', 'shared text, chars / screen-eligible'), ('sca', 'shared text, chars / all body'), ('sl_', 'shared text, code lines (prorated)')]
w('## 5. Files past one fifth (K+)')
w()
w('| Measure | Base | Landed | Newly past at landed | No longer past at landed |')
w('|---|---:|---:|---|---|')
for m, t in MEAS:
    b = JB['lists'][f'K+|{m}']; l = JL['lists'][f'K+|{m}']
    nw = [sh(p) for p in l if p not in b]; gone = [sh(p) for p in b if p not in l]
    w(f"| {t} | {len(b)} | {len(l)} | {', '.join(f'`{x}`' for x in nw) or '—'} | {', '.join(f'`{x}`' for x in gone) or '—'} |")
w()
w('Landed lists, by measure (share in brackets):')
w()
for m, t in MEAS:
    l = JL['lists'][f'K+|{m}']
    w(f"- **{t}** ({len(l)}): " + ', '.join(f"`{sh(p)}` {JL['perfile']['K+'][p][m]:.1%}" for p in l))
w()
w('## 6. Per-file table (K+), base | landed')
w()
w('Each cell: whole-body chars / eligible, whole-body chars / all, whole-body lines, shared chars / eligible, shared chars / all, shared lines. Bold: past one fifth.')
w()
w('| File | Base | Landed |')
w('|---|---|---|')
f5 = lambda v: f'**{v:.1%}**' if v > 0.2 else f'{v:.1%}'
for p in JB['perfile']['K+']:
    rb = JB['perfile']['K+'][p]; rl = JL['perfile']['K+'][p]
    if not rb['n'] and not rl['n']: continue
    cell = lambda r: ' / '.join(f5(r[m]) for m, _ in MEAS)
    w(f'| `{sh(p)}` | {cell(rb)} | {cell(rl)} |')
w()
w('## 7. Declarations counted at the landed tree (K+)')
w()
w('| Declaration | Lines | Code lines | Body chars | Shared chars | Class | Group | Manual |')
w('|---|---|---:|---:|---:|---|---|---|')
for d in DL: w(f'| `{sh(d[0])}` `{d[1]}` | {d[2]} | {d[3]} | {d[4]} | {d[5]} | {d[6]} | {d[7]} | {d[8]} |')
JT = json.load(open(os.path.join(wk, 'ledger3-tip.json'))); DT = rd('ledger3-tip-decls.tsv')
PT = {c[0]: c for c in rd('pairs3-tip.tsv')}; CT = {c[0]: c for c in rd('classify3-tip.tsv')}
w()
w('## 8. At the tip (the landed tree plus #98-#100; the 27 payback files unchanged)')
w()
key = lambda c: (c[1], c[2], c[3], c[7], c[8])
KL = {key(c): i for i, c in PL.items()}; KT = {key(c): i for i, c in PT.items()}
w(f'Pairs: landed {len(PL)}, tip {len(PT)}; only at the landed tree {len([k for k in KL if k not in KT])}; only at the tip {len([k for k in KT if k not in KL])}.')
w()
w('| Pair at one tree only | Tree | Cat | A | B | Class | Group | Shared |')
w('|---|---|---|---|---|---|---|---:|')
for k, i in KL.items():
    if k not in KT: c = PL[i]; g = CL[i]; w(f'| {i} | landed | {c[1]} | `{sh(c[2])}` `{c[3]}` | `{sh(c[7])}` `{c[8]}` | {g[2]} | {g[4]} | {c[13]} |')
for k, i in KT.items():
    if k not in KL: c = PT[i]; g = CT[i]; w(f'| {i} | tip | {c[1]} | `{sh(c[2])}` `{c[3]}` | `{sh(c[7])}` `{c[8]}` | {g[2]} | {g[4]} | {c[13]} |')
if set(KL) == set(KT): w('| none | | | | | | | |')
w()
totals(JT, 'Totals at the tip')
bygroup(DT, 'tip')
w('| Measure (K+) | Landed | Tip |')
w('|---|---:|---:|')
for m, t in MEAS: w(f"| {t} | {len(JL['lists'][f'K+|{m}'])} | {len(JT['lists'][f'K+|{m}'])} |")
w()
ML = {(d[0], d[1]): d[3:] for d in DL}; MT = {(d[0], d[1]): d[3:] for d in DT}
same = sum(1 for k in ML if MT.get(k) == ML[k])
w(f'K+ declaration rows: landed {len(DL)}, tip {len(DT)}; identical in everything but line numbers: {same}.')
print('tables written')
