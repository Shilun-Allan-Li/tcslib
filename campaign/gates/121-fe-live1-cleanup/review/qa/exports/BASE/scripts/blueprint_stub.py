r"""Give every uncovered declaration a blueprint entry, with the prose left to the LLM pass.

The dataset only contains declarations that have a blueprint entry: build_dataset.py
skips a theorem with no `\lean{...}` binding.  Interactive `blueprint-writer`
agents (see /blueprint-extract) write those entries by hand, prose included.  The
headless pipeline splits that job in two:

    1. this script writes the *mechanical* part of each entry -- environment,
       title, `\lean`, `\label`, `\leanok`, `\uses` -- from the work units of
       blueprint_enumerate.py, with a marked placeholder body;
    2. build_informal_statements.py (an LLM pass gated by statement_quality.py)
       writes the prose from the formal statement, and blueprint_restate.py
       --apply-only drops it into the entry, replacing the placeholder.

Entries are appended under a `\section{Additional declarations}` of the module's
chapter file (created with a chapter header when the file is new), exactly where
blueprint-writer would put them, so later interactive edits and this script
never fight over the same lines.  A stub body is recognisable by its marker
comment and by the placeholder sentence; scripts/dataset_check.py refuses a
dataset that still carries one.

Usage:
    python3 scripts/blueprint_enumerate.py          # first: plan the work units
    python3 scripts/blueprint_stub.py --dry-run     # what would be written
    python3 scripts/blueprint_stub.py               # write the stubs
    python3 scripts/blueprint_assemble.py           # then: wire new chapter files in
"""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

BASE = Path(__file__).resolve().parent.parent
WORK_DIR = BASE / "blueprint" / ".work"

import sys  # noqa: E402

sys.path.append(str(Path(__file__).resolve().parent))
from build_dataset import module_matches  # noqa: E402
CHAPTER_DIR = BASE / "blueprint" / "src" / "chapter"

STUB_MARKER = "% dataset-pipeline: stub -- prose pending build_informal_statements.py"
STUB_BODY = "Statement pending regeneration."
SECTION_HEADER = "%%% added by the blueprint pipeline"
SECTION_LINE = r"\section{Additional declarations}"

#: Labels are LaTeX macro arguments; keep the conservative character set the
#: existing chapters use.
LABEL_OK = re.compile(r"^[A-Za-z0-9_.']+$")


def humanize(name: str) -> str:
    """`OnlineLearning.finiteUpperImage_isOpen` -> `Finite upper image is open`."""
    short = name.rsplit(".", 1)[-1].rstrip("'")
    words = []
    for part in short.split("_"):
        part = re.sub(r"(?<=[a-z0-9])(?=[A-Z])", " ", part)
        part = re.sub(r"(?<=[A-Z])(?=[A-Z][a-z])", " ", part)
        words.extend(w for w in part.split(" ") if w)
    if not words:
        return short
    text = " ".join(words)
    text = text[0].upper() + text[1:].lower() if text.isupper() is False else text
    return text.replace("_", r"\_")


def tex_escape(text: str) -> str:
    return text.replace("_", r"\_").replace("&", r"\&").replace("#", r"\#").replace("%", r"\%")


def render_entry(decl: dict) -> str:
    lines = [f"\\begin{{{decl['env']}}}[{tex_escape(humanize(decl['name']))}]",
             f"\\lean{{{decl['name']}}}"]
    if LABEL_OK.match(decl["name"]):
        lines.append(f"\\label{{{decl['name']}}}")
    lines.append(r"\leanok")
    uses = [u for u in decl.get("uses", []) if u != decl["name"]]
    if uses:
        lines.append(f"\\uses{{{', '.join(uses)}}}")
    lines.append(STUB_MARKER)
    lines.append(STUB_BODY)
    lines.append(f"\\end{{{decl['env']}}}")
    return "\n".join(lines)


def chapter_header(unit: dict) -> str:
    area = re.sub(r"(?<=[a-z])(?=[A-Z])", " ", unit["area"])
    return "\n".join([
        f"\\chapter{{{tex_escape(area)} — {tex_escape(unit['chapter_title'])}}}",
        f"%%% generated by the blueprint pipeline from {unit['module']}",
        r"\section{Overview}",
        "",
        f"Declarations of the Lean module \\texttt{{{tex_escape(unit['module'])}}}.",
        "",
        r"\section{Declarations}",
        "",
    ])


def existing_bindings(text: str) -> set[str]:
    out: set[str] = set()
    for m in re.finditer(r"\\lean\{([^}]*)\}", text):
        for part in m.group(1).split(","):
            if part.strip():
                out.add(part.strip())
    return out


def write_unit(unit: dict, dry_run: bool) -> tuple[int, bool]:
    tex = BASE / unit["target_tex"]
    text = tex.read_text(encoding="utf-8") if tex.exists() else ""
    have = existing_bindings(text)
    decls = [d for d in unit["decls"] if d["name"] not in have]
    if not decls:
        return 0, tex.exists()
    entries = "\n\n".join(render_entry(d) for d in decls)
    if not text:
        new_text = chapter_header(unit) + "\n" + entries + "\n"
    elif SECTION_HEADER in text and SECTION_LINE in text:
        new_text = text.rstrip("\n") + "\n\n" + entries + "\n"
    else:
        new_text = (text.rstrip("\n") + "\n\n" + SECTION_HEADER + "\n" + SECTION_LINE
                    + "\n\n" + entries + "\n")
    if not dry_run:
        tex.parent.mkdir(parents=True, exist_ok=True)
        tex.write_text(new_text, encoding="utf-8")
    return len(decls), bool(text)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--module", action="append", default=None, metavar="MODULE",
                    help="only this module (full name, dotted suffix or area); repeatable")
    ap.add_argument("--only", nargs="+", default=None, metavar="NAME",
                    help="only these declarations")
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()

    manifest = WORK_DIR / "manifest.json"
    if not manifest.exists():
        print(f"ERROR: {manifest.relative_to(BASE)} not found; run "
              "scripts/blueprint_enumerate.py first.")
        return 1
    rows = json.loads(manifest.read_text(encoding="utf-8"))["units"]
    if args.module:
        rows = [r for r in rows if module_matches(r["module"], args.module)]
    total = created = appended = 0
    for row in rows:
        unit = json.loads((BASE / row["work_file"]).read_text(encoding="utf-8"))
        if args.only:
            unit["decls"] = [d for d in unit["decls"] if d["name"] in set(args.only)]
        n, existed = write_unit(unit, args.dry_run)
        if not n:
            continue
        total += n
        created += not existed
        appended += existed
        flag = "add " if existed else "NEW "
        print(f"  [{flag}] {unit['module']}: {n} stub(s) -> {unit['target_tex']}")
    verb = "would write" if args.dry_run else "wrote"
    print(f"\n{verb} {total} stub entries ({created} new chapter files, {appended} appended)")
    if total and not args.dry_run:
        print("next: python3 scripts/blueprint_assemble.py && "
              "python3 scripts/build_informal_statements.py")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
